/**
 * The mermaid backend: a model drawn as one Mermaid class diagram per
 * package. The mapping is in docs/architecture/mermaid-backend.md.
 *
 * @module
 */

import { create } from "@bufbuild/protobuf";
import {
	type Backend,
	type Description,
	fields,
	ir,
	lastSegment,
	params,
	protocol,
	Session,
	variants,
} from "@unmango/tdl-plugin";

/** What this backend is called, in a target block and as `tdl-gen-mermaid` on PATH. */
export const NAME = "mermaid";

/** The comment every diagram starts with. */
export const HEADER = "%% Code generated by tdl. DO NOT EDIT.";

const FORMATS = ["mermaid", "markdown"];

/** The mermaid backend. */
export const mermaid: Backend = {
	describe(): Description {
		return {
			name: NAME,
			version: "0.1.0",
			// Each request stands alone.
			reuse: true,
			directives: [
				// format("markdown") writes the diagram in a fenced block of a .md file.
				create(protocol.DirectiveSpecSchema, {
					name: "format",
					minArgs: 1,
					maxArgs: 1,
					argKinds: [ir.LiteralKind.STRING],
					placements: [protocol.Placement.BLOCK],
					values: FORMATS,
				}),
				// Draws a structure as a service, each field an rpc.
				create(protocol.DirectiveSpecSchema, {
					name: "service",
					placements: [protocol.Placement.DECL],
				}),
				// Tags a primitive of two type arguments, the request and the
				// response, that a service field applies to declare an rpc.
				create(protocol.DirectiveSpecSchema, {
					name: "rpc",
					placements: [protocol.Placement.DECL],
				}),
				// Tags a primitive of one type argument marking an rpc's request or
				// response streamed.
				create(protocol.DirectiveSpecSchema, {
					name: "stream",
					placements: [protocol.Placement.DECL],
				}),
			],
		};
	},

	/** Returns one file holding the package's class diagram. */
	generate(request: protocol.Request): protocol.Response {
		const s = new Session(request, "Mermaid");
		const id = packageId(s.model()?.package ?? "");
		const diagram = draw(s);

		const markdown = s.block("format")?.args[0]?.text === "markdown";
		const file = markdown
			? create(protocol.FileSchema, { path: `${id}.md`, content: encode(`\`\`\`mermaid\n${diagram}\`\`\`\n`) })
			: create(protocol.FileSchema, { path: `${id}.mmd`, content: encode(diagram) });
		return s.response([file]);
	},
};

const encode = (text: string) => new TextEncoder().encode(text);

/** A package's segments joined with `_`; a model with no package is `model`. */
export function packageId(pkg: string): string {
	return pkg === "" ? "model" : pkg.replaceAll(".", "_");
}

// The diagram: a class per drawn declaration, then the edges between them.
function draw(s: Session): string {
	const own = s.own();
	const d = new Diagram(s, own);
	for (const decl of own) {
		d.decl(decl);
	}
	for (const decl of own) {
		d.relations(decl);
	}
	// Mermaid refuses a diagram with no statement.
	if (d.lines.length === 0) {
		d.lines.push(`  note "${s.model()?.package || "The model"} declares nothing drawn as a class"`);
	}
	return [HEADER, "classDiagram", ...d.lines, ...d.namespaces(), ...d.edges, ""].join("\n");
}

class Diagram {
	readonly lines: string[] = [];
	readonly edges: string[] = [];
	readonly #s: Session;
	// Every class id taken, so a variant's id never merges with another class.
	readonly #taken: Set<string>;
	// The class id each drawn declaration and fielded variant took.
	readonly #ids = new Map<ir.Decl | ir.Variant, string>();
	// The class id each drawn extern took, by its index in Model.externs.
	readonly #externs = new Map<number, string>();

	constructor(s: Session, own: readonly ir.Decl[]) {
		this.#s = s;
		this.#taken = new Set(own.map((d) => lastSegment(d.meta?.name ?? "")));
	}

	decl(d: ir.Decl): void {
		const name = lastSegment(d.meta?.name ?? "");
		const cls = this.#classId(name);
		const id = cls + typeParams(d) + (cls === name ? "" : `["${name}"]`);
		switch (d.node.case) {
			case "structure": {
				this.#ids.set(d, cls);
				if (this.#s.tagged(d.directives, "service")) {
					this.#class(
						id,
						"service",
						fields(d).map((f) => this.#rpc(f) ?? this.#member(f)),
					);
					return;
				}
				const stereotype = d.node.value.kind === ir.StructKind.MIXIN ? "mixin" : undefined;
				// An included field is drawn on its mixin, joined by one edge.
				this.#class(id, stereotype, this.#members(fields(d).filter((f) => !f.includedFrom)));
				return;
			}
			case "enumeration": {
				const vs = variants(d);
				this.#ids.set(d, cls);
				if (!this.#s.declView(d)?.fielded) {
					this.#class(
						id,
						"enumeration",
						vs.map((v) => v.meta?.name ?? ""),
					);
					return;
				}
				this.#class(id, "union", []);
				for (const v of vs) {
					const vname = v.meta?.name ?? "";
					const vid = this.#variantId(name, vname);
					this.#ids.set(v, vid);
					this.#class(`${vid}["${vname}"]`, undefined, this.#members(v.fields));
					this.edges.push(`  ${cls} <|-- ${vid}`);
				}
				return;
			}
			case "newtype":
				this.#ids.set(d, cls);
				this.#class(id, "newtype", [`+${this.#spell(d.node.value.base)}`]);
				return;
			case "class":
				this.#ids.set(d, cls);
				this.#class(id, "interface", this.#members(d.node.value.fields));
				return;
			default:
			// An alias is expanded where it is used, and a primitive or a unit
			// has no class.
		}
	}

	/**
	 * The edges from a drawn declaration: one inheritance edge per mixin it
	 * includes, a realization edge per class of the model's it conforms to,
	 * and an edge per drawn declaration or extern each field names.
	 */
	relations(d: ir.Decl): void {
		const from = this.#ids.get(d);
		if (from === undefined) {
			return;
		}
		switch (d.node.case) {
			case "structure": {
				const service = this.#s.tagged(d.directives, "service");
				const mixins = new Set<ir.Decl>();
				for (const f of fields(d)) {
					const mixin = f.includedFrom && this.#s.declAt(f.includedFrom);
					if (mixin) {
						mixins.add(mixin);
					}
				}
				for (const m of mixins) {
					const id = this.#ids.get(m);
					if (id !== undefined) {
						this.edges.push(`  ${id} <|-- ${from}`);
					}
				}
				this.#conforms(from, d.node.value.conforms);
				// A service's rpcs draw no edges, and an included field's edges are
				// its mixin's.
				this.#fieldEdges(
					from,
					fields(d).filter((f) => !f.includedFrom && !(service && this.#rpc(f) !== undefined)),
				);
				return;
			}
			case "enumeration":
				this.#conforms(from, d.node.value.conforms);
				for (const v of variants(d)) {
					const vid = this.#ids.get(v);
					if (vid !== undefined) {
						this.#fieldEdges(vid, v.fields);
					}
				}
				return;
			case "class":
				this.#fieldEdges(from, d.node.value.fields);
				return;
			default:
		}
	}

	/** The externs fields name, each package's in one `namespace` block. */
	namespaces(): string[] {
		const byPackage = new Map<string, string[]>();
		for (const [i, id] of this.#externs) {
			const e = this.#s.model()?.externs[i];
			const pkg = packageId(e?.package ?? "");
			const label = e && id !== e.name ? `["${e.name}"]` : "";
			byPackage.set(pkg, [...(byPackage.get(pkg) ?? []), `    class ${id}${label}`]);
		}
		return [...byPackage].flatMap(([pkg, classes]) => [`  namespace ${pkg} {`, ...classes, "  }"]);
	}

	#conforms(from: string, refs: readonly ir.ClassRef[]): void {
		for (const r of refs) {
			const c = r.class && this.#s.declAt(r.class);
			const id = c && this.#ids.get(c);
			if (id !== undefined) {
				this.edges.push(`  ${from} ..|> ${id}`);
			}
		}
	}

	// An edge per drawn declaration or extern each field names, labelled with
	// the field's name: a composition for an owned field, else an
	// association, its far end's cardinality read from the field's outermost
	// type.
	#fieldEdges(from: string, fs: readonly ir.Field[]): void {
		for (const f of fs) {
			if (!f.type) {
				continue;
			}
			const arrow = f.owned ? "*--" : "-->";
			const many = this.#cardinality(f.type);
			const name = f.meta?.name ?? "";
			const targets = [
				...this.#s
					.typeReferences([f.type])
					.map((d) => this.#ids.get(d))
					.filter((id) => id !== undefined),
				...this.#externsNamed(f.type),
			];
			for (const to of targets) {
				this.edges.push(`  ${from} "1" ${arrow} "${many}" ${to} : ${name}`);
			}
		}
	}

	#cardinality(id: ir.ID): string {
		switch (this.#s.typeView(id)?.form) {
			case protocol.Form.LIST:
			case protocol.Form.SET:
			case protocol.Form.MAP:
				return "*";
			case protocol.Form.OPTION:
			case protocol.Form.NULLABLE:
				return "0..1";
			default:
				return "1";
		}
	}

	// The class ids of the externs a type names, through its arguments and
	// with aliases expanded, each once, drawing each on first use.
	#externsNamed(id: ir.ID): string[] {
		const out: string[] = [];
		const walk = (x: ir.ID) => {
			const t = this.#expanded(x);
			if (!t) {
				return;
			}
			for (const a of t.args) {
				walk(a);
			}
			if (t.extern) {
				const cls = this.#externId(t.extern.index);
				if (cls !== undefined && !out.includes(cls)) {
					out.push(cls);
				}
			}
		};
		walk(id);
		return out;
	}

	#externId(i: number): string | undefined {
		const e = this.#s.model()?.externs[i];
		if (!e) {
			return undefined;
		}
		let id = this.#externs.get(i);
		if (id === undefined) {
			id = this.#free(KEYWORDS.has(e.name) ? `${e.name}_` : e.name);
			this.#externs.set(i, id);
		}
		return id;
	}

	// A declaration's class id: its name, or for a name Mermaid reserves, the
	// name with `_` appended until nothing else holds it, labeled with the name.
	#classId(name: string): string {
		return KEYWORDS.has(name) ? this.#free(`${name}_`) : name;
	}

	// A fielded variant's class id, `Enum_Variant`, or with `_` appended until
	// nothing else holds it.
	#variantId(name: string, variant: string): string {
		return this.#free(`${name}_${variant}`);
	}

	// The id with `_` appended until no class holds it, then taken.
	#free(id: string): string {
		let free = id;
		while (this.#taken.has(free)) {
			free += "_";
		}
		this.#taken.add(free);
		return free;
	}

	#class(id: string, stereotype: string | undefined, members: string[]): void {
		const body = stereotype ? [`<<${stereotype}>>`, ...members] : members;
		if (body.length === 0) {
			this.lines.push(`  class ${id}`);
			return;
		}
		this.lines.push(`  class ${id} {`, ...body.map((m) => `    ${m}`), "  }");
	}

	#members(fs: readonly ir.Field[]): string[] {
		return fs.map((f) => this.#member(f));
	}

	#member(f: ir.Field): string {
		return `+${this.#spell(f.type)} ${f.meta?.name ?? ""}`;
	}

	// A service's field as a method: an rpc's request and response as its
	// parameter and result, or undefined when its type is no rpc.
	#rpc(f: ir.Field): string | undefined {
		const t = this.#expanded(f.type);
		const [req, res] = t?.args ?? [];
		if (!t || !this.#ctorTagged(t, "rpc") || t.args.length !== 2 || !req || !res) {
			return undefined;
		}
		return `+${f.meta?.name ?? ""}(${this.#rpcArg(req)}) ${this.#rpcArg(res)}`;
	}

	#rpcArg(id: ir.ID): string {
		const t = this.#expanded(id);
		const [inner] = t?.args ?? [];
		if (t && inner && t.args.length === 1 && this.#ctorTagged(t, "stream")) {
			return `stream ${this.#spell(inner)}`;
		}
		return this.#spell(id);
	}

	#ctorTagged(t: ir.Type, name: string): boolean {
		if (t.extern) {
			const e = this.#s.model()?.externs[t.extern.index];
			return e !== undefined && this.#s.tagged(e.directives, name);
		}
		const c = t.ctor && this.#s.declAt(t.ctor);
		return c !== undefined && c.node.case === "primitive" && this.#s.tagged(c.directives, name);
	}

	#type(id: ir.ID | undefined): ir.Type | undefined {
		return id && this.#s.model()?.types[id.index];
	}

	// A type with its aliases expanded, as the analysis resolves it.
	#expanded(id: ir.ID | undefined): ir.Type | undefined {
		return id && this.#type(this.#s.typeView(id)?.id ?? id);
	}

	// A type as a member writes it, in Mermaid's generic spelling.
	#spell(id: ir.ID | undefined): string {
		if (!id) {
			return "";
		}
		const view = this.#s.typeView(id);
		const sub = (x: ir.ID | undefined) => this.#spell(x);
		switch (view?.form) {
			case protocol.Form.PRIMITIVE:
			case protocol.Form.PARAM:
				return view.name + this.#args(view.id ?? id);
			case protocol.Form.LIST:
				return `List~${sub(view.elem)}~`;
			case protocol.Form.SET:
				return `Set~${sub(view.elem)}~`;
			case protocol.Form.MAP:
				return `Map~${sub(view.key)},${sub(view.elem)}~`;
			case protocol.Form.OPTION:
				return `Option~${sub(view.elem)}~`;
			case protocol.Form.NULLABLE:
				return `${sub(view.elem)} | null`;
			case protocol.Form.NAMED: {
				const d = view.decl && this.#s.declAt(view.decl);
				return lastSegment(d?.meta?.name ?? id.name) + this.#args(view.id ?? id);
			}
			case protocol.Form.EXTERN: {
				const e = view.extern && this.#s.model()?.externs[view.extern.index];
				return (e ? e.name : lastSegment(id.name)) + this.#args(view.id ?? id);
			}
			case protocol.Form.UNIT: {
				const t = this.#type(view.id ?? id);
				const u = t?.unit && this.#s.model()?.units[t.unit.index];
				return u?.wrote || id.name;
			}
			default:
				return lastSegment(id.name);
		}
	}

	// A type's arguments, as `~A,B~`, or nothing.
	#args(id: ir.ID): string {
		const args = this.#type(id)?.args ?? [];
		return args.length === 0 ? "" : `~${args.map((a) => this.#spell(a)).join(",")}~`;
	}
}

// The words Mermaid's class diagram grammar refuses as a class id, which
// neither backticks nor quotes admit.
const KEYWORDS = new Set([
	"call",
	"callback",
	"class",
	"classDef",
	"classDiagram",
	"click",
	"cssClass",
	"href",
	"link",
	"namespace",
	"note",
	"style",
]);

// A declaration's type parameters, as `~T~`, or nothing.
function typeParams(d: ir.Decl): string {
	const ps = params(d);
	return ps.length === 0 ? "" : `~${ps.map((p) => p.name).join(",")}~`;
}
