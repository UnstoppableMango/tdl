/**
 * The mermaid backend: a model drawn as one Mermaid class diagram per
 * package. The mapping is in docs/architecture/mermaid-backend.md.
 *
 * @module
 */

import { create } from "@bufbuild/protobuf";
import {
	type Backend,
	type Description,
	fields,
	ir,
	lastSegment,
	params,
	protocol,
	Session,
	variants,
} from "@unmango/tdl-plugin";

/** What this backend is called, in a target block and as `tdl-gen-mermaid` on PATH. */
export const NAME = "mermaid";

/** The comment every diagram starts with. */
export const HEADER = "%% Code generated by tdl. DO NOT EDIT.";

const FORMATS = ["mermaid", "markdown"];

/** The mermaid backend. */
export const mermaid: Backend = {
	describe(): Description {
		return {
			name: NAME,
			version: "0.1.0",
			// Each request stands alone.
			reuse: true,
			directives: [
				// format("markdown") writes the diagram in a fenced block of a .md file.
				create(protocol.DirectiveSpecSchema, {
					name: "format",
					minArgs: 1,
					maxArgs: 1,
					argKinds: [ir.LiteralKind.STRING],
					placements: [protocol.Placement.BLOCK],
					values: FORMATS,
				}),
				// Draws a structure as a service, each field an rpc.
				create(protocol.DirectiveSpecSchema, {
					name: "service",
					placements: [protocol.Placement.DECL],
				}),
				// Tags a primitive of two type arguments, the request and the
				// response, that a service field applies to declare an rpc.
				create(protocol.DirectiveSpecSchema, {
					name: "rpc",
					placements: [protocol.Placement.DECL],
				}),
				// Tags a primitive of one type argument marking an rpc's request or
				// response streamed.
				create(protocol.DirectiveSpecSchema, {
					name: "stream",
					placements: [protocol.Placement.DECL],
				}),
			],
		};
	},

	/** Returns one file holding the package's class diagram. */
	generate(request: protocol.Request): protocol.Response {
		const s = new Session(request, "Mermaid");
		const id = packageId(s.model()?.package ?? "");
		const diagram = draw(s);

		const markdown = s.block("format")?.args[0]?.text === "markdown";
		const file = markdown
			? create(protocol.FileSchema, { path: `${id}.md`, content: encode(`\`\`\`mermaid\n${diagram}\`\`\`\n`) })
			: create(protocol.FileSchema, { path: `${id}.mmd`, content: encode(diagram) });
		return s.response([file]);
	},
};

const encode = (text: string) => new TextEncoder().encode(text);

/** A package's segments joined with `_`; a model with no package is `model`. */
export function packageId(pkg: string): string {
	return pkg === "" ? "model" : pkg.replaceAll(".", "_");
}

// The diagram: a class per drawn declaration, then the edges between them.
function draw(s: Session): string {
	const d = new Diagram(s);
	for (const decl of s.own()) {
		d.decl(decl);
	}
	// Mermaid refuses a diagram with no statement.
	if (d.lines.length === 0) {
		d.lines.push(`  note "${s.model()?.package || "The model"} declares nothing drawn as a class"`);
	}
	return [HEADER, "classDiagram", ...d.lines, ...d.edges, ""].join("\n");
}

class Diagram {
	readonly lines: string[] = [];
	readonly edges: string[] = [];
	readonly #s: Session;

	constructor(s: Session) {
		this.#s = s;
	}

	decl(d: ir.Decl): void {
		const name = lastSegment(d.meta?.name ?? "");
		const id = name + typeParams(d);
		switch (d.node.case) {
			case "structure": {
				if (this.#s.tagged(d.directives, "service")) {
					this.#class(
						id,
						"service",
						fields(d).map((f) => this.#rpc(f)),
					);
					return;
				}
				const stereotype = d.node.value.kind === ir.StructKind.MIXIN ? "mixin" : undefined;
				this.#class(id, stereotype, this.#members(fields(d)));
				return;
			}
			case "enumeration": {
				const vs = variants(d);
				if (!this.#s.declView(d)?.fielded) {
					this.#class(
						id,
						"enumeration",
						vs.map((v) => v.meta?.name ?? ""),
					);
					return;
				}
				this.#class(id, "union", []);
				for (const v of vs) {
					const vname = v.meta?.name ?? "";
					this.#class(`${name}_${vname}["${vname}"]`, undefined, this.#members(v.fields));
					this.edges.push(`  ${name} <|-- ${name}_${vname}`);
				}
				return;
			}
			case "newtype":
				this.#class(id, "newtype", [`+${this.#spell(d.node.value.base)}`]);
				return;
			case "class":
				this.#class(id, "interface", this.#members(d.node.value.fields));
				return;
			default:
			// An alias is expanded where it is used, and a primitive or a unit
			// has no class.
		}
	}

	#class(id: string, stereotype: string | undefined, members: string[]): void {
		const body = stereotype ? [`<<${stereotype}>>`, ...members] : members;
		if (body.length === 0) {
			this.lines.push(`  class ${id}`);
			return;
		}
		this.lines.push(`  class ${id} {`, ...body.map((m) => `    ${m}`), "  }");
	}

	#members(fs: readonly ir.Field[]): string[] {
		return fs.map((f) => `+${this.#spell(f.type)} ${f.meta?.name ?? ""}`);
	}

	// A service's field as a method: an rpc's request and response as its
	// parameter and result, or an attribute when its type is no rpc.
	#rpc(f: ir.Field): string {
		const t = this.#type(f.type);
		const [req, res] = t?.args ?? [];
		if (!t || !this.#ctorTagged(t, "rpc") || t.args.length !== 2 || !req || !res) {
			return this.#members([f])[0] as string;
		}
		return `+${f.meta?.name ?? ""}(${this.#rpcArg(req)}) ${this.#rpcArg(res)}`;
	}

	#rpcArg(id: ir.ID): string {
		const t = this.#type(id);
		const [inner] = t?.args ?? [];
		if (t && inner && t.args.length === 1 && this.#ctorTagged(t, "stream")) {
			return `stream ${this.#spell(inner)}`;
		}
		return this.#spell(id);
	}

	#ctorTagged(t: ir.Type, name: string): boolean {
		if (t.extern) {
			const e = this.#s.model()?.externs[t.extern.index];
			return e !== undefined && this.#s.tagged(e.directives, name);
		}
		const c = t.ctor && this.#s.declAt(t.ctor);
		return c !== undefined && c.node.case === "primitive" && this.#s.tagged(c.directives, name);
	}

	#type(id: ir.ID | undefined): ir.Type | undefined {
		return id && this.#s.model()?.types[id.index];
	}

	// A type as a member writes it, in Mermaid's generic spelling.
	#spell(id: ir.ID | undefined): string {
		if (!id) {
			return "";
		}
		const view = this.#s.typeView(id);
		const sub = (x: ir.ID | undefined) => this.#spell(x);
		switch (view?.form) {
			case protocol.Form.PRIMITIVE:
			case protocol.Form.PARAM:
				return view.name + this.#args(view.id ?? id);
			case protocol.Form.LIST:
				return `List~${sub(view.elem)}~`;
			case protocol.Form.SET:
				return `Set~${sub(view.elem)}~`;
			case protocol.Form.MAP:
				return `Map~${sub(view.key)},${sub(view.elem)}~`;
			case protocol.Form.OPTION:
				return `Option~${sub(view.elem)}~`;
			case protocol.Form.NULLABLE:
				return `${sub(view.elem)} | null`;
			case protocol.Form.NAMED: {
				const d = view.decl && this.#s.declAt(view.decl);
				return lastSegment(d?.meta?.name ?? id.name) + this.#args(view.id ?? id);
			}
			case protocol.Form.EXTERN: {
				const e = view.extern && this.#s.model()?.externs[view.extern.index];
				return (e ? e.name : lastSegment(id.name)) + this.#args(view.id ?? id);
			}
			case protocol.Form.UNIT: {
				const t = this.#type(view.id ?? id);
				const u = t?.unit && this.#s.model()?.units[t.unit.index];
				return u?.wrote || id.name;
			}
			default:
				return lastSegment(id.name);
		}
	}

	// A type's arguments, as `~A,B~`, or nothing.
	#args(id: ir.ID): string {
		const args = this.#type(id)?.args ?? [];
		return args.length === 0 ? "" : `~${args.map((a) => this.#spell(a)).join(",")}~`;
	}
}

// A declaration's type parameters, as `~T~`, or nothing.
function typeParams(d: ir.Decl): string {
	const ps = params(d);
	return ps.length === 0 ? "" : `~${ps.map((p) => p.name).join(",")}~`;
}
