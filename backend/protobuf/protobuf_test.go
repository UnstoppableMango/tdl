func TestFieldlessEnum(t *testing.T) {
	b := irtest.New("shop")
	b.Own(enum("Status", variant("Active"), variant("InProgress")))
	b.Own(value("Ticket", irtest.Field("status", b.Named("Option", b.Named("Status")))))

	contains(t, compile(t, generate(t, b)),
		"enum Status { STATUS_UNSPECIFIED = 0; STATUS_ACTIVE = 1; STATUS_IN_PROGRESS = 2; }",
		"optional Status status = 1;",
	)
}

// An enum whose variants carry fields is a oneof of nested messages, and a
// reference inside one to a declaration sharing a variant's name has to
// reach past the variant.
func TestFieldedEnumIsAOneof(t *testing.T) {
	b := irtest.New("shop")
	b.Own(value("Card", irtest.Field("pan", b.Named("string"))))
	b.Own(enum("Payment",
		variant("Card", irtest.Field("last4", b.Named("string")), irtest.Field("card", b.Named("Card"))),
		variant("Cash"),
	))
	b.Own(value("Checkout", irtest.Field("payment", b.Named("Option", b.Named("Payment")))))

	contains(t, compile(t, generate(t, b)),
		"message Payment {",
		"message Card { string last4 = 1; .shop.Card card = 2; }",
		"message Cash { }",
		"oneof variant { Card card = 1; Cash cash = 2; }",
		"Payment payment = 1;",
	)
}

func TestNewtypesAndAliasesExpand(t *testing.T) {
	b := irtest.New("shop")
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "Sku"}, Node: &ir.Decl_Newtype{Newtype: &ir.Newtype{Base: b.Named("string")}}})
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "Email"}, Node: &ir.Decl_Newtype{Newtype: &ir.Newtype{Base: b.Named("Sku")}}})
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "Tags"}, Node: &ir.Decl_Alias{Alias: &ir.Alias{Target: b.Named("List", b.Named("Sku"))}}})
	b.Own(value("Item",
		irtest.Field("sku", b.Named("Sku")),
		irtest.Field("tags", b.Named("Tags")),
		irtest.Field("byEmail", b.Named("Map", b.Named("Email"), b.Named("int"))),
	))

	src := compile(t, generate(t, b))
	contains(t, src, "string sku = 1;", "repeated string tags = 2;", "map<string, int64> by_email = 3;")
	absent(t, src, "Sku", "Email", "Tags")
}

func TestNumbers(t *testing.T) {
	b := irtest.New("shop")
	pinned := irtest.Field("b", b.Named("string"))
	pinned.Directives = []*ir.Directive{number("10")}
	b.Own(value("Pinned", irtest.Field("a", b.Named("string")), pinned, irtest.Field("c", b.Named("string"))))

	cash := variant("Cash")
	cash.Directives = []*ir.Directive{number("5")}
	b.Own(enum("Payment", variant("Card", irtest.Field("last4", b.Named("string"))), cash))

	closed := variant("Closed")
	closed.Directives = []*ir.Directive{number("9")}
	b.Own(enum("Status", variant("Open"), closed))

	contains(t, compile(t, generate(t, b)),
		"string a = 1; string b = 10; string c = 3;",
		"Card card = 1; Cash cash = 5;",
		"STATUS_OPEN = 1; STATUS_CLOSED = 9;",
	)
}

func TestNumbersProtobufRefuses(t *testing.T) {
	for name, n := range map[string]string{
		"a collision":         "1",
		"the reserved range":  "19500",
		"zero":                "0",
		"past the last field": "536870912",
	} {
		t.Run(name, func(t *testing.T) {
			b := irtest.New("shop")
			pinned := irtest.Field("b", b.Named("string"))
			pinned.Directives = []*ir.Directive{number(n)}
			b.Own(value("Broken", irtest.Field("a", b.Named("string")), pinned))
			b.Own(value("Fine", irtest.Field("a", b.Named("string"))))

			resp := generate(t, b)
			if len(resp.GetDiagnostics()) != 1 {
				t.Errorf("diagnostics = %+v", resp.GetDiagnostics())
			}
			src := compile(t, resp)
			absent(t, src, "message Broken")
			contains(t, src, "message Fine")
		})
	}
}

// A shape protobuf cannot express is a warning, the declaration reaching it
// is skipped, and so is everything naming that declaration.
func TestUnsupportedShapesAreSkipped(t *testing.T) {
	for _, tt := range []struct {
		name string
		typ  func(b *irtest.Builder) *ir.ID
	}{
		{"a list of lists", func(b *irtest.Builder) *ir.ID { return b.Named("List", b.Named("List", b.Named("int"))) }},
		{"a list of optionals", func(b *irtest.Builder) *ir.ID { return b.Named("List", b.Named("Option", b.Named("int"))) }},
		{"an optional list", func(b *irtest.Builder) *ir.ID { return b.Named("Option", b.Named("List", b.Named("int"))) }},
		{"an optional optional", func(b *irtest.Builder) *ir.ID {
			return b.Named("Nullable", b.Named("Option", b.Named("int")))
		}},
		{"a map keyed by bytes", func(b *irtest.Builder) *ir.ID { return b.Named("Map", b.Named("bytes"), b.Named("int")) }},
		{"a map keyed by a message", func(b *irtest.Builder) *ir.ID { return b.Named("Map", b.Named("Fine"), b.Named("int")) }},
		{"a map of lists", func(b *irtest.Builder) *ir.ID {
			return b.Named("Map", b.Named("string"), b.Named("List", b.Named("int")))
		}},
	} {
		t.Run(tt.name, func(t *testing.T) {
			b := irtest.New("shop")
			b.Own(value("Fine", irtest.Field("a", b.Named("string"))))
			b.Own(value("Broken", irtest.Field("x", tt.typ(b))))
			b.Own(value("Holder", irtest.Field("broken", b.Named("Broken"))))

			resp := generate(t, b)
			if len(resp.GetDiagnostics()) != 2 {
				t.Errorf("want a warning for Broken and one for Holder: %+v", resp.GetDiagnostics())
			}
			for _, d := range resp.GetDiagnostics() {
				if d.GetSeverity() != plugin.Severity_SEVERITY_WARNING {
					t.Errorf("severity = %v", d.GetSeverity())
				}
			}
			src := compile(t, resp)
			absent(t, src, "message Broken", "message Holder")
			contains(t, src, "message Fine")
		})
	}
}

