func generate(t *testing.T, b *irtest.Builder) *plugin.Response {
	t.Helper()
	resp, err := protobuf.Backend{}.Generate(context.Background(), &plugin.Request{
		Target: protobuf.Name,
		Model:  b.Model,
	})
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	return resp
}

// compile returns the response's one file, and asserts protobuf accepts it.
//
// Compiling rather than parsing is the assertion that matters: a reference
// to a message a skipped declaration left behind parses, and so does a map
// keyed by a message.
func compile(t *testing.T, resp *plugin.Response) string {
	t.Helper()
	if len(resp.GetFiles()) != 1 {
		t.Fatalf("files = %d, diagnostics = %+v", len(resp.GetFiles()), resp.GetDiagnostics())
	}
	f := resp.GetFiles()[0]
	c := protocompile.Compiler{Resolver: protocompile.WithStandardImports(&protocompile.SourceResolver{
		Accessor: protocompile.SourceAccessorFromMap(map[string]string{f.GetPath(): string(f.GetContent())}),
	})}
	if _, err := c.Compile(context.Background(), f.GetPath()); err != nil {
		t.Errorf("%s does not compile: %v\n%s", f.GetPath(), err, f.GetContent())
	}
	return string(f.GetContent())
}

// contains asserts on the output with runs of whitespace collapsed.
func contains(t *testing.T, src string, wants ...string) {
	t.Helper()
	flat := collapse(src)
	for _, want := range wants {
		if !strings.Contains(flat, collapse(want)) {
			t.Errorf("output missing %q:\n%s", want, src)
		}
	}
}

func absent(t *testing.T, src string, unwanted ...string) {
	t.Helper()
	for _, u := range unwanted {
		if strings.Contains(src, u) {
			t.Errorf("output has %q:\n%s", u, src)
		}
	}
}

func collapse(s string) string { return strings.Join(strings.Fields(s), " ") }

func structure(name string, kind ir.StructKind, fields ...*ir.Field) *ir.Decl {
	return &ir.Decl{
		Meta: &ir.Meta{Name: name},
		Node: &ir.Decl_Structure{Structure: &ir.Struct{Kind: kind, Fields: fields}},
	}
}

func value(name string, fields ...*ir.Field) *ir.Decl {
	return structure(name, ir.StructKind_STRUCT_KIND_VALUE, fields...)
}

func enum(name string, variants ...*ir.Variant) *ir.Decl {
	return &ir.Decl{
		Meta: &ir.Meta{Name: name},
		Node: &ir.Decl_Enumeration{Enumeration: &ir.Enum{Variants: variants}},
	}
}

func variant(name string, fields ...*ir.Field) *ir.Variant {
	return &ir.Variant{Meta: &ir.Meta{Name: name}, Fields: fields}
}

func renamed(n string) []*ir.Directive {
	return []*ir.Directive{{
		Name: "name", Target: protobuf.Name, Args: []*ir.Literal{irtest.Text(n)},
		Position: &ir.Position{Filename: "shop.tdl", Line: 7},
	}}
}

func number(n string) *ir.Directive {
	return &ir.Directive{Name: "number", Target: protobuf.Name, Args: []*ir.Literal{{Kind: ir.LiteralKind_LITERAL_KIND_INT, Text: n}}}
}

func TestDescribe(t *testing.T) {
	d := protobuf.Backend{}.Describe()
	if d.Name != "protobuf" || !d.Reuse {
		t.Errorf("description = %+v", d)
	}
	declared := map[string]bool{}
	for _, spec := range d.Directives {
		declared[spec.GetName()] = true
	}
	for _, want := range []string{"package", "name", "number"} {
		if !declared[want] {
			t.Errorf("directive %q is acted on but not declared", want)
		}
	}
}

func TestMessages(t *testing.T) {
	b := irtest.New("shop.billing")
	b.Own(value("LineItem",
		irtest.Field("sku", b.Named("string")),
		irtest.Field("quantity", b.Named("int")),
	))
	b.Own(structure("Order", ir.StructKind_STRUCT_KIND_ENTITY,
		irtest.Field("id", b.Named("uuid")),
		irtest.Field("placedAt", b.Named("instant")),
		irtest.Field("items", b.Named("List", b.Named("LineItem"))),
		irtest.Field("tags", b.Named("Set", b.Named("string"))),
		irtest.Field("totals", b.Named("Map", b.Named("string"), b.Named("decimal"))),
		irtest.Field("note", b.Named("Option", b.Named("string"))),
		irtest.Field("took", b.Named("duration")),
		irtest.Field("shipOn", b.Named("Nullable", b.Named("date"))),
		irtest.Field("receipt", b.Named("bytes")),
		irtest.Field("paid", b.Named("bool")),
		irtest.Field("first", b.Named("Option", b.Named("LineItem"))),
	))

	resp := generate(t, b)
	if len(resp.GetDiagnostics()) != 0 {
		t.Errorf("diagnostics = %+v", resp.GetDiagnostics())
	}
	src := compile(t, resp)
	if path := resp.GetFiles()[0].GetPath(); path != "shop/billing/billing.proto" {
		t.Errorf("path = %q", path)
	}
	contains(t, src,
		"// Code generated by tdl. DO NOT EDIT.",
		`syntax = "proto3";`,
		"package shop.billing;",
		`import "google/protobuf/duration.proto";`,
		`import "google/protobuf/timestamp.proto";`,
		"message LineItem { string sku = 1; int64 quantity = 2; }",
		"string id = 1;",
		"google.protobuf.Timestamp placed_at = 2;",
		"repeated LineItem items = 3;",
		"repeated string tags = 4;",
		"map<string, string> totals = 5;",
		"optional string note = 6;",
		"google.protobuf.Duration took = 7;",
		"optional string ship_on = 8;",
		"bytes receipt = 9;",
		"bool paid = 10;",
		// A message field already has presence.
		"LineItem first = 11;",
	)
}

