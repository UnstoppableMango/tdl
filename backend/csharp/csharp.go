// Package csharp generates C# source from a resolved model: a sealed record
// for each struct, a C# enum for each fieldless enum, an abstract record
// closed over nested variant records for each enum with fields, and a
// readonly record struct for each newtype. The mapping is in
// docs/design/csharp-backend.md.
package csharp

import (
	"context"
	"fmt"
	"slices"
	"strings"

	"github.com/unstoppablemango/tdl/backend/internal/emit"
	"github.com/unstoppablemango/tdl/ir"
	"github.com/unstoppablemango/tdl/plugin"
)

// Name names this backend in a target block and as tdl-gen-csharp.
const Name = "csharp"

// Backend implements [plugin.Backend].
type Backend struct{}

func (Backend) Describe() plugin.Description {
	str := []ir.LiteralKind{ir.LiteralKind_LITERAL_KIND_STRING}
	return plugin.Description{
		Name:    Name,
		Version: "0.1.0",
		// Each request stands alone.
		Reuse: true,
		Directives: []*plugin.DirectiveSpec{
			// The namespace, on the target block.
			{Name: "namespace", MinArgs: 1, MaxArgs: 1, ArgKinds: str, Placements: plugin.On(plugin.OnBlock)},
			// One file for every declaration, on the target block.
			{Name: "file", MinArgs: 1, MaxArgs: 1, ArgKinds: str, Placements: plugin.On(plugin.OnBlock)},
			// The C# identifier for a declaration, field, or variant.
			{Name: "name", MinArgs: 1, MaxArgs: 1, ArgKinds: str, Placements: plugin.OnMembers()},
			// The namespace and type a declaration maps to, declared
			// elsewhere.
			{Name: "foreign", MinArgs: 2, MaxArgs: 2, ArgKinds: []ir.LiteralKind{str[0], str[0]}, Placements: plugin.On(plugin.OnDecl)},
			// The fields identifying an entity. ArgKinds constrains by
			// position, so key checks that each is a name.
			{Name: "key", MinArgs: 1, MaxArgs: -1, Placements: plugin.On(plugin.OnDecl)},
			// An attribute, by its namespace and name, on a declaration or
			// on every declaration from the target block.
			{Name: "attribute", MinArgs: 2, MaxArgs: 2, ArgKinds: []ir.LiteralKind{str[0], str[0]}, Repeatable: true, Placements: plugin.On(plugin.OnBlock, plugin.OnDecl)},
		},
	}
}

// header starts every file. <auto-generated> turns the nullable context
// off, so #nullable follows it. The pragma silences use of an obsolete
// member inside the file, since generated equality reads deprecated fields,
// and an obsolete required member, which C# otherwise refuses.
const header = `// <auto-generated>
// Code generated by tdl. DO NOT EDIT.
// </auto-generated>
#nullable enable
#pragma warning disable CS0612, CS0618, CS9042
`

// equalityType is the class each namespace declares once, comparing
// collections and bytes by their contents.
const equalityType = "TdlEquality"

type generator struct {
	*emit.Session

	// ns is the generated namespace.
	ns string

	// names maps each declaration that declares a type to its C# name, and
	// owners each C# name to the declaration taking it.
	names  map[*ir.Decl]string
	owners map[string]string

	// foreign and externs map a declaration and an extern to the type
	// another assembly or namespace declares for it, written qualified.
	foreign map[*ir.Decl]string
	externs map[*ir.Extern]string

	// attributes are the target block's attributes, which every
	// declaration carries.
	attributes []string
}

// piece is one declaration's output.
type piece struct {
	name string
	text string

	// equality is whether it reads the namespace's TdlEquality.
	equality bool
}

// Generate returns one file per declaration the model owns, or one file
// holding them all when the target block names it.
func (Backend) Generate(_ context.Context, req *plugin.Request) (*plugin.Response, error) {
	g := &generator{
		Session: emit.NewSession(req, "C#"),
		names:   map[*ir.Decl]string{},
		owners:  map[string]string{},
	}

	ns, err := g.namespace()
	if err != nil {
		g.Warn(err)
		return g.Response(nil), nil
	}
	g.ns = ns
	g.Externs = true
	g.planForeign()
	g.attributes = g.attributesOf(g.blockDirectives())

	own := g.Own()
	skipped := map[*ir.Decl]bool{}
	for _, d := range own {
		if err := g.claim(d); err != nil {
			g.Warn(err)
			skipped[d] = true
		}
	}

	out := map[*ir.Decl]*piece{}
	// Each declaration's warnings are held until the cascade decides
	// whether it is emitted.
	held := map[*ir.Decl][]*plugin.Diagnostic{}
	for _, d := range own {
		if skipped[d] {
			continue
		}
		mark := len(g.Diags)
		p, err := g.decl(d)
		if err != nil {
			g.Diags = g.Diags[:mark]
			g.Warn(err)
			skipped[d] = true
			continue
		}
		held[d] = slices.Clone(g.Diags[mark:])
		g.Diags = g.Diags[:mark]
		if p != nil {
			out[d] = p
		}
	}
	g.Cascade(own, skipped)

	var emitted []*piece
	equality := false
	for _, d := range own {
		if p := out[d]; p != nil && !skipped[d] {
			g.Diags = append(g.Diags, held[d]...)
			emitted = append(emitted, p)
			equality = equality || p.equality
		}
	}
	if len(emitted) == 0 {
		return g.Response(nil), nil
	}
	if equality {
		emitted = append(emitted, &piece{name: equalityType, text: equalitySource})
	}

	if dir, ok := g.Block("file"); ok {
		var b strings.Builder
		g.start(&b)
		for _, p := range emitted {
			b.WriteString("\n" + p.text)
		}
		return g.Response([]*plugin.File{{Path: dir.GetArgs()[0].GetText(), Content: []byte(b.String())}}), nil
	}
	files := make([]*plugin.File, 0, len(emitted))
	for _, p := range emitted {
		var b strings.Builder
		g.start(&b)
		b.WriteString("\n" + p.text)
		files = append(files, &plugin.File{
			Path:    strings.TrimPrefix(p.name, "@") + ".g.cs",
			Content: []byte(b.String()),
		})
	}
	return g.Response(files), nil
}

// start writes what every file begins with.
func (g *generator) start(b *strings.Builder) {
	b.WriteString(header)
	fmt.Fprintf(b, "\nnamespace %s;\n", g.ns)
}

// claim records the C# name a declaration takes, before any is rendered,
// so a reference to one declared later is spelled the same.
func (g *generator) claim(d *ir.Decl) error {
	if _, ok := g.foreign[d]; ok || d.GetStructure() == nil && d.GetEnumeration() == nil && d.GetNewtype() == nil {
		return nil
	}
	pos := d.GetMeta().GetPosition()
	name := d.GetMeta().GetName()
	typ, err := g.typeName(d)
	if err != nil {
		return err
	}
	if strings.TrimPrefix(typ, "@") == equalityType {
		return emit.Unsupported(pos, "%s would be named %s in C#, which the generated equality class takes; a name directive resolves it", name, typ)
	}
	if other, ok := g.owners[typ]; ok {
		return emit.Unsupported(pos, "%s would be named %s in C#, and %s already is; a name directive on either resolves it", name, typ, other)
	}
	g.names[d] = typ
	g.owners[typ] = name
	return nil
}

// decl renders one declaration, or nil for one that declares nothing.
func (g *generator) decl(d *ir.Decl) (*piece, error) {
	pos := d.GetMeta().GetPosition()
	name := d.GetMeta().GetName()

	if _, ok := g.foreign[d]; ok {
		// Another assembly declares it.
		return nil, nil
	}
	switch {
	case d.GetClass() != nil:
		return nil, emit.Lost(emit.LossClass, pos, "%s is a class, and classes are not generated yet", name)
	case d.GetStructure() == nil && d.GetEnumeration() == nil && d.GetNewtype() == nil:
		// A primitive, an alias, and a unit declare nothing: an alias is
		// expanded where it is used, and C# has no units.
		return nil, nil
	case len(d.Params()) > 0:
		return nil, emit.Lost(emit.LossGeneric, pos, "%s is parameterized, and generics are not generated yet", name)
	}

	typ := g.names[d]
	p := &piece{name: typ}
	var b strings.Builder
	doc(&b, "", d.GetMeta())
	obsolete(&b, "", d.GetMeta())
	for _, a := range g.attributes {
		b.WriteString(a + "\n")
	}
	for _, a := range g.attributesOf(d.GetDirectives()) {
		b.WriteString(a + "\n")
	}
	key, keyed := g.Find(d.GetDirectives(), "key")
	if keyed && d.GetStructure() == nil {
		g.Lossy(emit.LossKey, key.GetPosition(), "%s has a key, and only an entity is identified by one", name)
		key = nil
	}
	var err error
	switch {
	case d.GetNewtype() != nil:
		p.equality, err = g.newtype(&b, d, typ)
	case d.GetStructure() != nil:
		p.equality, err = g.record(&b, name, typ, "", "public sealed partial record "+typ, d.Fields(), nil, d, key)
	case emit.Fielded(d.GetEnumeration()):
		p.equality, err = g.union(&b, d, typ)
	default:
		err = g.enum(&b, d, typ)
	}
	if err != nil {
		return nil, err
	}

	g.WarnConstraints(d)
	p.text = b.String()
	return p, nil
}

// newtype renders a newtype as a readonly record struct holding its base.
func (g *generator) newtype(b *strings.Builder, d *ir.Decl, typ string) (bool, error) {
	if strings.TrimPrefix(typ, "@") == "Value" {
		return false, emit.Unsupported(d.GetMeta().GetPosition(),
			"%s would be named Value in C#, which its own property takes; a name directive resolves it", d.GetMeta().GetName())
	}
	base, err := g.typ(d.GetNewtype().GetBase(), nil)
	if err != nil {
		return false, err
	}
	fmt.Fprintf(b, "public readonly partial record struct %s(%s Value)", typ, base.text)
	if base.cmp == "" {
		b.WriteString(";\n")
		return false, nil
	}
	cmps := []comparer{{name: "_value", typ: base.text, expr: base.cmp}}
	b.WriteString("\n{\n")
	writeComparers(b, "    ", cmps)
	b.WriteString("\n")
	fmt.Fprintf(b, "    public bool Equals(%s other) => _value.Equals(this.Value, other.Value);\n\n", typ)
	writeHash(b, "    ", []property{{name: "Value"}}, map[string]string{"Value": "_value"})
	b.WriteString("}\n")
	return true, nil
}

// enum renders a fieldless enum as a C# enum.
func (g *generator) enum(b *strings.Builder, d *ir.Decl, typ string) error {
	seen := map[string]bool{}
	var lines strings.Builder
	for _, v := range d.GetEnumeration().GetVariants() {
		vname, err := g.variantName(d, typ, v, seen)
		if err != nil {
			return err
		}
		doc(&lines, "    ", v.GetMeta())
		obsolete(&lines, "    ", v.GetMeta())
		fmt.Fprintf(&lines, "    %s,\n", vname)
	}
	fmt.Fprintf(b, "public enum %s\n{\n%s}\n", typ, lines.String())
	return nil
}

// union renders an enum whose variants carry fields as an abstract record
// closed by a private constructor, with a sealed nested record per variant.
func (g *generator) union(b *strings.Builder, d *ir.Decl, typ string) (bool, error) {
	name := d.GetMeta().GetName()
	variants := d.GetEnumeration().GetVariants()

	// A variant's name shadows a type of the same name inside the enum.
	seen := map[string]bool{}
	names := make([]string, len(variants))
	for i, v := range variants {
		vname, err := g.variantName(d, typ, v, seen)
		if err != nil {
			return false, err
		}
		names[i] = vname
	}
	shadow := map[string]bool{}
	for _, n := range names {
		shadow[strings.TrimPrefix(n, "@")] = true
	}

	equality := false
	var body strings.Builder
	for i, v := range variants {
		body.WriteString("\n")
		doc(&body, "    ", v.GetMeta())
		obsolete(&body, "    ", v.GetMeta())
		eq, err := g.record(&body, name+"."+v.GetMeta().GetName(), names[i], "    ",
			"public sealed partial record "+names[i]+" : "+typ, v.GetFields(), shadow, nil, nil)
		if err != nil {
			return false, err
		}
		equality = equality || eq
	}
	fmt.Fprintf(b, "public abstract partial record %s\n{\n    private %s() { }\n%s}\n", typ, typ, body.String())
	return equality, nil
}

// property is one field as a C# property.
type property struct {
	name     string
	typ      csType
	required bool
	field    *ir.Field

	// init is the default the property is initialized to, or "".
	init string
}

// comparer is a static field holding the comparer a property is compared
// by.
type comparer struct {
	name, typ, expr string
}

// record renders a record: decl is its declaration line, and owner its name
// as the model spells it, for messages. It reports whether the record
// writes its own equality. A key directive on the entity d writes a Key
// method, and a key record after the record when it names several fields.
func (g *generator) record(b *strings.Builder, owner, typ, indent, decl string, fields []*ir.Field, shadow map[string]bool, d *ir.Decl, key *ir.Directive) (bool, error) {
	props, err := g.properties(owner, typ, fields, shadow)
	if err != nil {
		return false, err
	}
	var method, after string
	if key != nil {
		if method, after, err = g.key(d, typ, props, key); err != nil {
			g.Warn(err)
		}
	}
	if len(props) == 0 {
		b.WriteString(indent + decl + ";\n" + after)
		return false, nil
	}

	taken := map[string]bool{}
	for _, p := range props {
		taken[strings.TrimPrefix(p.name, "@")] = true
	}
	var cmps []comparer
	byProp := map[string]string{}
	for _, p := range props {
		if p.typ.cmp == "" {
			continue
		}
		n := "_" + lowerFirst(strings.TrimPrefix(p.name, "@"))
		for taken[n] {
			n += "_"
		}
		taken[n] = true
		cmps = append(cmps, comparer{name: n, typ: p.typ.text, expr: p.typ.cmp})
		byProp[p.name] = n
	}

	in := indent + "    "
	b.WriteString(indent + decl + "\n" + indent + "{\n")
	if len(cmps) > 0 {
		writeComparers(b, in, cmps)
		b.WriteString("\n")
	}
	for i, p := range props {
		f := p.field
		if i > 0 && (len(emit.Doc(f.GetMeta())) > 0 || len(emit.Doc(props[i-1].field.GetMeta())) > 0) {
			b.WriteString("\n")
		}
		doc(b, in, f.GetMeta())
		obsolete(b, in, f.GetMeta())
		req := ""
		if p.required {
			req = "required "
		}
		init := ""
		if p.init != "" {
			init = " = " + p.init + ";"
		}
		fmt.Fprintf(b, "%spublic %s%s %s { get; init; }%s\n", in, req, p.typ.text, p.name, init)
	}
	if method != "" {
		b.WriteString("\n" + in + method + "\n")
	}
	if len(cmps) > 0 {
		b.WriteString("\n")
		fmt.Fprintf(b, "%spublic bool Equals(%s? other) =>\n", in, typ)
		fmt.Fprintf(b, "%s    object.ReferenceEquals(this, other)\n", in)
		fmt.Fprintf(b, "%s    || other is not null", in)
		for _, p := range props {
			cmp := byProp[p.name]
			if cmp == "" {
				cmp = defaultComparer(p.typ.text)
			}
			fmt.Fprintf(b, "\n%s    && %s.Equals(this.%s, other.%s)", in, cmp, p.name, p.name)
		}
		b.WriteString(";\n\n")
		writeHash(b, in, props, byProp)
	}
	b.WriteString(indent + "}\n" + after)
	return len(cmps) > 0, nil
}

// properties maps fields to properties, refusing the names C# would.
func (g *generator) properties(owner, typ string, fields []*ir.Field, shadow map[string]bool) ([]property, error) {
	var props []property
	seen := map[string]string{}
	for _, f := range fields {
		pos := f.GetMeta().GetPosition()
		fname := f.GetMeta().GetName()
		n, err := g.memberName(g.FieldName(f, upperFirst))
		if err != nil {
			return nil, emit.Unsupported(pos, "%s.%s %v", owner, fname, err)
		}
		bare := strings.TrimPrefix(n, "@")
		switch {
		case bare == strings.TrimPrefix(typ, "@"):
			return nil, emit.Unsupported(pos, "%s.%s would be the property %s in C#, which a member of %s cannot be named; a name directive resolves it", owner, fname, n, typ)
		case reservedMembers[bare]:
			return nil, emit.Unsupported(pos, "%s.%s would be the property %s in C#, which every record declares; a name directive resolves it", owner, fname, n)
		case seen[bare] != "":
			return nil, emit.Unsupported(pos, "%s.%s and %s would both be the property %s in C#; a name directive on either resolves it", owner, fname, seen[bare], n)
		}
		seen[bare] = fname

		t, required, err := g.fieldType(f, shadow)
		if err != nil {
			return nil, err
		}
		p := property{name: n, typ: t, required: required, field: f}
		if lit := f.GetDefaultValue(); lit != nil {
			init, err := g.defaultValue(f.GetType(), lit, shadow)
			if err != nil {
				g.Warn(err)
			} else {
				p.init, p.required = init, false
			}
		}
		props = append(props, p)
	}
	return props, nil
}

// writeComparers writes the static fields holding each comparer.
func writeComparers(b *strings.Builder, indent string, cmps []comparer) {
	for _, c := range cmps {
		fmt.Fprintf(b, "%sprivate static readonly global::System.Collections.Generic.IEqualityComparer<%s> %s = %s;\n", indent, c.typ, c.name, c.expr)
	}
}

// writeHash writes GetHashCode over every property, through its comparer
// when it has one.
func writeHash(b *strings.Builder, indent string, props []property, byProp map[string]string) {
	fmt.Fprintf(b, "%spublic override int GetHashCode()\n%s{\n", indent, indent)
	fmt.Fprintf(b, "%s    var hash = new global::System.HashCode();\n", indent)
	for _, p := range props {
		if cmp := byProp[p.name]; cmp != "" {
			fmt.Fprintf(b, "%s    hash.Add(this.%s, %s);\n", indent, p.name, cmp)
		} else {
			fmt.Fprintf(b, "%s    hash.Add(this.%s);\n", indent, p.name)
		}
	}
	fmt.Fprintf(b, "%s    return hash.ToHashCode();\n%s}\n", indent, indent)
}

// doc writes a node's documentation as an XML doc comment.
func doc(b *strings.Builder, indent string, m *ir.Meta) {
	lines := emit.Doc(m)
	switch len(lines) {
	case 0:
	case 1:
		fmt.Fprintf(b, "%s/// <summary>%s</summary>\n", indent, xmlEscape(lines[0]))
	default:
		fmt.Fprintf(b, "%s/// <summary>\n", indent)
		for _, line := range lines {
			fmt.Fprintf(b, "%s\n", strings.TrimRight(indent+"/// "+xmlEscape(line), " "))
		}
		fmt.Fprintf(b, "%s/// </summary>\n", indent)
	}
}

// obsolete writes the Obsolete attribute on a deprecated node.
func obsolete(b *strings.Builder, indent string, m *ir.Meta) {
	reason, ok := emit.Deprecated(m)
	switch {
	case !ok:
	case reason == "":
		fmt.Fprintf(b, "%s[global::System.Obsolete]\n", indent)
	default:
		fmt.Fprintf(b, "%s[global::System.Obsolete(%s)]\n", indent, str(reason))
	}
}

var xmlEscaper = strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;")

func xmlEscape(s string) string { return xmlEscaper.Replace(s) }
