// An extern, a declaration another TDL package owns, is imported rather
// than declared. `foreign(module, name)` names the module and what it
// exports, for a hand-written module. Otherwise, when the dependency has a
// target block for the same backend, the extern is what that block
// generates, imported from its file by a path relative to this one. Both
// files are placed by their blocks' `out` directives, each relative to the
// file declaring the block.

// Import is one name a module imports.
type Import struct {
	Module, Name string
	At           *ir.Position
}

// Uses holds the imports one declaration needs, by the name each binds.
type Uses map[string]Import

// Extern is the name an extern is imported as, recording its import in
// uses. ext ends the specifier of a dependency's generated file, ".js" or
// ".zod.js".
func Extern(s *emit.Session, uses Uses, r *emit.Ref, ext string) (string, error) {
	own := r.Extern.GetDirectives()
	if f, ok := s.Find(own, "foreign"); ok {
		args := f.GetArgs()
		if len(args) != 2 {
			return "", emit.Unsupported(f.GetPosition(),
				"foreign takes a module and a name, and %d argument(s) were given", len(args))
		}
		return uses.Add(r.Name, args[0].GetText(), args[1].GetText(), f.GetPosition())
	}

	for _, dep := range s.Model.GetImports() {
		if dep.GetPackage() != r.Extern.GetPackage() {
			continue
		}
		// A block holding only declaration directives reaches the
		// extern alone.
		if len(plugin.Directives(s.Target, dep.GetDirectives())) == 0 &&
			len(plugin.Directives(s.Target, own)) == 0 {
			break
		}
		module, err := dependencyModule(s, r, dep, ext)
		if err != nil {
			return "", err
		}
		return uses.Add(r.Name, module, ExternName(s, r), r.Pos)
	}
	return "", emit.Unsupported(r.Pos,
		"%s is declared in another package with no %s target block, and no foreign directive maps it", r.Name, s.Target)
}

// ExternName is the name an extern is imported as: the one its foreign
// directive names, or else the one its dependency's block generates.
func ExternName(s *emit.Session, r *emit.Ref) string {
	own := r.Extern.GetDirectives()
	if f, ok := s.Find(own, "foreign"); ok && len(f.GetArgs()) == 2 {
		return f.GetArgs()[1].GetText()
	}
	if name, ok := s.Text(own, "name"); ok {
		return name
	}
	return emit.Pascal(emit.LastSegment(r.Extern.GetName()))
}

// dependencyModule is the specifier this file imports a dependency's
// generated file by.
func dependencyModule(s *emit.Session, r *emit.Ref, dep *ir.Import, ext string) (string, error) {
	depOut, ok := s.Find(dep.GetDirectives(), OutDirective)
	if !ok || len(depOut.GetArgs()) == 0 {
		return "", emit.Unsupported(r.Pos,
			"%s is generated by a %s target block with no out directive, so this file cannot import it by a relative path", r.Name, s.Target)
	}
	rootOut, ok := s.Block(OutDirective)
	if !ok || len(rootOut.GetArgs()) == 0 {
		return "", emit.Unsupported(r.Pos,
			"%s is generated into a dependency's out directory, and this target block has no out directive to import it from", r.Name)
	}
	spec, err := Relative(rootOut, depOut, dep.GetPackage(), ext)
	if err != nil {
		return "", emit.Unsupported(r.Pos, "%s is generated in %s, which has no path relative to %s", r.Name, Placed(depOut), Placed(rootOut))
	}
	return spec, nil
}

// Add records an import of name from module, for what describes. Whether
// it collides with another declaration's import or with a declared name
// waits for [Conflicts], when the emitted declarations are known.
func (uses Uses) Add(what, module, name string, at *ir.Position) (string, error) {
	if module == "" {
		return "", emit.Unsupported(at, "the foreign mapping of %s has no module", what)
	}
	if !CanName(name) {
		return "", emit.Unsupported(at, "%s is mapped to %q, which cannot name a TypeScript type", what, name)
	}
	if have, ok := uses[name]; ok && have.Module != module {
		return "", emit.Unsupported(at, "%s would import %s from %s, and %s already names the one from %s",
			what, name, module, name, have.Module)
	}
	uses[name] = Import{Module: module, Name: name, At: at}
	return name, nil
}

// Conflicts skips each declaration, in source order, importing a name that
// an emitted declaration declares or an earlier declaration imports from
// another module, reporting each through skip. It reports whether it
// skipped any, since the cascade then runs again.
func Conflicts(own []*ir.Decl, skipped map[*ir.Decl]bool, declares map[*ir.Decl][]string, uses map[*ir.Decl]Uses, skip func(error)) bool {
	declared := map[string]string{}
	for _, d := range own {
		if !skipped[d] {
			for _, n := range declares[d] {
				declared[n] = d.GetMeta().GetName()
			}
		}
	}

	skippedAny := false
	taken := Uses{}
	for _, d := range own {
		if skipped[d] {
			continue
		}
		if err := conflict(d.GetMeta().GetName(), uses[d], declared, taken); err != nil {
			skip(err)
			skipped[d] = true
			skippedAny = true
			continue
		}
		maps.Copy(taken, uses[d])
	}
	return skippedAny
}

// conflict is why one declaration's imports cannot be written, or nil.
func conflict(decl string, uses Uses, declared map[string]string, taken Uses) error {
	for _, name := range slices.Sorted(maps.Keys(uses)) {
		im := uses[name]
		if other, ok := declared[name]; ok {
			return emit.Unsupported(im.At, "%s would import %s, which %s declares", decl, name, other)
		}
		if have, ok := taken[name]; ok && have.Module != im.Module {
			return emit.Unsupported(im.At, "%s would import %s from %s, and %s already names the one from %s",
				decl, name, im.Module, name, have.Module)
		}
	}
	return nil
}

// Lines writes one import statement per module, names sorted, for the
// imports the emitted declarations use. keyword is "import type" for
// types alone, or "import" for values.
func Lines(imports Uses, keyword string) string {
	byModule := map[string][]string{}
	for _, im := range imports {
		byModule[im.Module] = append(byModule[im.Module], im.Name)
	}

	var b strings.Builder
	for _, m := range slices.Sorted(maps.Keys(byModule)) {
		names := byModule[m]
		slices.Sort(names)
		b.WriteString(keyword + " { " + strings.Join(names, ", ") + " } from " + strconv.Quote(m) + ";\n")
	}
	return b.String()
}
