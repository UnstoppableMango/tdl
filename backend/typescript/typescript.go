// Package typescript generates TypeScript type declarations from a
// resolved model.
//
// docs/design/schema-backends.md has the mapping and the reasons for it.
// What it emits describes JSON on the wire rather than runtime objects:
// interfaces and type aliases, no classes, and no code. That is why a set
// is an array, a map is a Record, and every primitive TypeScript has no
// JSON form for is a string. An enum whose variants carry fields is a
// discriminated union on a `kind` field holding the variant's name, which
// a `discriminant` directive renames.
package typescript

import (
	"context"
	"fmt"
	"regexp"
	"strconv"
	"strings"

	"github.com/unstoppablemango/tdl/backend/internal/emit"
	"github.com/unstoppablemango/tdl/ir"
	"github.com/unstoppablemango/tdl/plugin"
)

// Name is what this backend is called, in a target block and as
// tdl-gen-typescript on PATH.
const Name = "typescript"

// Backend implements [plugin.Backend].
type Backend struct{}

func (Backend) Describe() plugin.Description {
	str := []ir.LiteralKind{ir.LiteralKind_LITERAL_KIND_STRING}
	return plugin.Description{
		Name:    Name,
		Version: "0.1.0",
		// Each request is answered from the request alone.
		Reuse: true,
		Directives: []*plugin.DirectiveSpec{
			// The TypeScript name for a type, a property, or a variant's
			// interface.
			{Name: "name", MinArgs: 1, MaxArgs: 1, ArgKinds: str},
			// The property a discriminated union switches on. Written on the
			// target block it is the default, and on an enum it wins.
			{Name: "discriminant", MinArgs: 1, MaxArgs: 1, ArgKinds: str},
		},
	}
}

// scalars maps a TDL primitive to the TypeScript type its JSON value has.
// JSON has no bytes, decimal, UUID, or time, so each is the string a
// consumer parses; an int is a number, which is exact to 2^53.
var scalars = map[string]string{
	"string":   "string",
	"int":      "number",
	"bool":     "boolean",
	"bytes":    "string",
	"decimal":  "string",
	"uuid":     "string",
	"instant":  "string",
	"date":     "string",
	"duration": "string",
}

// reserved is the words TypeScript does not accept as a type's name.
// An emitted file is a module, where `await` is reserved too.
var reserved = map[string]bool{}

func init() {
	for _, w := range strings.Fields(`
		any as await boolean break case catch class const continue debugger default
		delete do else enum export extends false finally for function if
		implements import in instanceof interface let never new null number
		object package private protected public return static string super
		switch symbol this throw true try type typeof undefined unknown var
		void while with yield`) {
		reserved[w] = true
	}
}

var ident = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// defaultDiscriminant is the property a discriminated union switches on
// when no directive names one.
const defaultDiscriminant = "kind"

type generator struct {
	*emit.Session

	// discriminant is the target block's default.
	discriminant string

	// names is every type name declared, with the declaration that
	// declared it.
	names map[string]string
}

// Generate returns one .ts file holding every declaration the model owns.
func (Backend) Generate(_ context.Context, req *plugin.Request) (*plugin.Response, error) {
	g := &generator{
		Session:      emit.NewSession(req, "TypeScript"),
		discriminant: defaultDiscriminant,
		names:        map[string]string{},
	}
	if d, ok := g.Block("discriminant"); ok {
		g.discriminant = d.GetArgs()[0].GetText()
	}

	own := g.Own()
	texts := map[*ir.Decl]string{}
	skipped := map[*ir.Decl]bool{}
	for _, d := range own {
		text, err := g.decl(d)
		if err != nil {
			g.Warn(err)
			skipped[d] = true
			continue
		}
		texts[d] = text
	}
	g.Cascade(own, skipped)

	var blocks []string
	for _, d := range own {
		if text := texts[d]; text != "" && !skipped[d] {
			blocks = append(blocks, text)
		}
	}
	if len(blocks) == 0 {
		return g.Response(nil), nil
	}

	var b strings.Builder
	b.WriteString("// Code generated by tdl. DO NOT EDIT.\n")
	for _, block := range blocks {
		b.WriteString("\n")
		b.WriteString(block)
	}

	path := "model.ts"
	if pkg := req.GetModel().GetPackage(); pkg != "" {
		path = emit.LastSegment(pkg) + ".ts"
	}
	return g.Response([]*plugin.File{{Path: path, Content: []byte(b.String())}}), nil
}

// decl renders one declaration, or "" for one that declares nothing.
func (g *generator) decl(d *ir.Decl) (string, error) {
	pos := d.GetMeta().GetPosition()
	name := d.GetMeta().GetName()

	switch {
	case d.GetClass() != nil:
		return "", emit.Unsupported(pos, "%s is a class, and classes are not generated yet", name)
	case d.GetUnit() != nil:
		return "", emit.Unsupported(pos, "%s is a unit, and units are not generated yet", name)
	case d.GetStructure() == nil && d.GetEnumeration() == nil && d.GetNewtype() == nil:
		// An alias is expanded where it is used, and a model's own
		// primitive names an opaque root; neither declares anything.
		return "", nil
	}
	if len(d.Params()) > 0 {
		return "", emit.Unsupported(pos, "%s is parameterized, and generics are not generated yet", name)
	}

	var b strings.Builder
	var declared []string
	var err error
	switch e := d.GetEnumeration(); {
	case d.GetNewtype() != nil:
		declared, err = g.newtype(&b, d)
	case d.GetStructure() != nil:
		declared, err = g.iface(&b, g.DeclName(d, emit.Pascal), d.GetMeta(), "", "", d.Fields())
	case emit.Fielded(e):
		declared, err = g.union(&b, d)
	default:
		declared = g.literals(&b, d)
	}
	if err != nil {
		return "", err
	}

	local := map[string]bool{}
	for _, n := range declared {
		if !ident.MatchString(n) || reserved[n] {
			return "", emit.Unsupported(pos, "%s would be named %s in TypeScript, which cannot name a type", name, n)
		}
		if local[n] {
			return "", emit.Unsupported(pos, "%s would declare %s in TypeScript twice", name, n)
		}
		local[n] = true
		if other, ok := g.names[n]; ok {
			return "", emit.Unsupported(pos, "%s would declare %s in TypeScript, and %s already does", name, n, other)
		}
	}
	for _, n := range declared {
		g.names[n] = name
	}
	g.WarnConstraints(d)
	return b.String(), nil
}

// newtype renders a newtype as an alias for its base. A branded type would
// say more, and would make every value parsed from JSON need a cast.
func (g *generator) newtype(b *strings.Builder, d *ir.Decl) ([]string, error) {
	ref, err := g.Resolve(d.GetNewtype().GetBase())
	if err != nil {
		return nil, err
	}
	base, err := g.typ(ref)
	if err != nil {
		return nil, err
	}
	name := g.DeclName(d, emit.Pascal)
	comment(b, "", d.GetMeta())
	fmt.Fprintf(b, "export type %s = %s;\n", name, base)
	return []string{name}, nil
}

// iface renders an interface. An entity, a value, and a mixin differ in
// what they mean and not in what they emit. A variant's interface passes
// the discriminant and its value, which come first.
func (g *generator) iface(b *strings.Builder, name string, meta *ir.Meta, disc, tag string, fields []*ir.Field) ([]string, error) {
	var body strings.Builder
	seen := map[string]bool{}
	if disc != "" {
		seen[disc] = true
		fmt.Fprintf(&body, "  %s: %s;\n", property(disc), strconv.Quote(tag))
	}

	for _, f := range fields {
		ref, err := g.Resolve(f.GetType())
		if err != nil {
			return nil, err
		}
		prop := g.FieldName(f, asWritten)
		if seen[prop] {
			if prop == disc {
				return nil, emit.Unsupported(f.GetMeta().GetPosition(),
					"%s.%s takes the name of the discriminant, and a discriminant directive can rename it", name, prop)
			}
			return nil, emit.Unsupported(f.GetMeta().GetPosition(), "%s has two properties named %s in TypeScript", name, prop)
		}
		seen[prop] = true

		line, err := g.property(prop, ref)
		if err != nil {
			return nil, err
		}
		comment(&body, "  ", f.GetMeta())
		fmt.Fprintf(&body, "  %s\n", line)
	}

	comment(b, "", meta)
	fmt.Fprintf(b, "export interface %s {\n%s}\n", name, body.String())
	return []string{name}, nil
}

// literals renders an enum whose variants carry no fields as a union of
// their names, which is what one looks like in JSON.
func (g *generator) literals(b *strings.Builder, d *ir.Decl) []string {
	name := g.DeclName(d, emit.Pascal)
	variants := d.GetEnumeration().GetVariants()

	values := make([]string, len(variants))
	for i, v := range variants {
		values[i] = strconv.Quote(v.GetMeta().GetName())
	}
	typ := strings.Join(values, " | ")
	if typ == "" {
		typ = "never"
	}

	comment(b, "", d.GetMeta())
	fmt.Fprintf(b, "export type %s = %s;\n", name, typ)
	return []string{name}
}

// union renders an enum where any variant carries fields: an interface per
// variant, each holding the discriminant with the variant's name as its
// value, and a union of them.
func (g *generator) union(b *strings.Builder, d *ir.Decl) ([]string, error) {
	name := g.DeclName(d, emit.Pascal)
	disc := g.discriminant
	if s, ok := g.Text(d.GetDirectives(), "discriminant"); ok {
		disc = s
	}

	declared := []string{name}
	var members []string
	var ifaces strings.Builder
	for _, v := range d.GetEnumeration().GetVariants() {
		member := name + emit.Pascal(v.GetMeta().GetName())
		if n, ok := g.Text(v.GetDirectives(), "name"); ok {
			member = n
		}
		ifaces.WriteString("\n")
		if _, err := g.iface(&ifaces, member, v.GetMeta(), disc, v.GetMeta().GetName(), v.GetFields()); err != nil {
			return nil, err
		}
		members = append(members, member)
		declared = append(declared, member)
	}

	comment(b, "", d.GetMeta())
	fmt.Fprintf(b, "export type %s = %s;\n", name, strings.Join(members, " | "))
	b.WriteString(ifaces.String())
	return declared, nil
}

// property renders a property: `?` when the key may be absent, and
// `| null` when the value may be null.
func (g *generator) property(name string, r *emit.Ref) (string, error) {
	optional, nullable := false, false
	for r.Form == emit.Option || r.Form == emit.Nullable {
		if r.Form == emit.Option {
			optional = true
		} else {
			nullable = true
		}
		r = r.Elem
	}

	typ, err := g.typ(r)
	if err != nil {
		return "", err
	}
	if nullable {
		typ += " | null"
	}
	q := ""
	if optional {
		q = "?"
	}
	return fmt.Sprintf("%s%s: %s;", property(name), q, typ), nil
}

// typ is the TypeScript type for a reference. An optional value inside a
// collection is one that may be null, since JSON has no absent element.
func (g *generator) typ(r *emit.Ref) (string, error) {
	switch r.Form {
	case emit.Prim:
		typ, ok := scalars[r.Name]
		if !ok {
			return "", emit.Unsupported(r.Pos, "primitive %s has no TypeScript type", r.Name)
		}
		return typ, nil
	case emit.List, emit.Set:
		elem, err := g.typ(r.Elem)
		if err != nil {
			return "", err
		}
		if strings.Contains(elem, " | ") {
			elem = "(" + elem + ")"
		}
		return elem + "[]", nil
	case emit.Map:
		return g.record(r)
	case emit.Option, emit.Nullable:
		inner, err := g.typ(r.Elem)
		if err != nil {
			return "", err
		}
		if strings.HasSuffix(inner, " | null") {
			return inner, nil
		}
		return inner + " | null", nil
	}
	return g.DeclName(r.Decl, emit.Pascal), nil
}

// record renders a map as a Record. A JSON object's keys are strings, so a
// key is anything that is a string or a number in JSON, or a fieldless
// enum, whose Record is Partial because a map need not hold every variant.
func (g *generator) record(r *emit.Ref) (string, error) {
	kx, err := g.Expand(r.Key)
	if err != nil {
		return "", err
	}
	key, err := g.typ(r.Key)
	if err != nil {
		return "", err
	}
	val, err := g.typ(r.Elem)
	if err != nil {
		return "", err
	}

	switch {
	case kx.Form == emit.Prim && (scalars[kx.Name] == "string" || scalars[kx.Name] == "number"):
		return "Record<" + key + ", " + val + ">", nil
	case kx.Form == emit.Named && kx.Decl.GetEnumeration() != nil && !emit.Fielded(kx.Decl.GetEnumeration()):
		return "Partial<Record<" + key + ", " + val + ">>", nil
	}
	return "", emit.Unsupported(r.Pos, "a TypeScript record key is a string, a number, or a fieldless enum, and this one is %s", key)
}

func asWritten(name string) string { return name }

// property quotes a property name that is not an identifier.
func property(name string) string {
	if ident.MatchString(name) {
		return name
	}
	return strconv.Quote(name)
}

// comment writes a node's documentation, and its deprecation, as a JSDoc
// comment, which is what an editor reads.
func comment(b *strings.Builder, indent string, meta *ir.Meta) {
	lines := emit.Doc(meta)
	if reason, ok := emit.Deprecated(meta); ok {
		if len(lines) > 0 {
			lines = append(lines, "")
		}
		lines = append(lines, strings.TrimSpace("@deprecated "+reason))
	}
	if len(lines) == 0 {
		return
	}
	fmt.Fprintf(b, "%s/**\n", indent)
	for _, line := range lines {
		if line == "" {
			fmt.Fprintf(b, "%s *\n", indent)
			continue
		}
		fmt.Fprintf(b, "%s * %s\n", indent, strings.ReplaceAll(line, "*/", "* /"))
	}
	fmt.Fprintf(b, "%s */\n", indent)
}
