// An extern, a declaration another TDL package owns, is imported as a type
// rather than declared. `foreign(module, name)` names the module and the
// type it exports, for a hand-written module. Otherwise, when the
// dependency has a typescript target block, the extern is the type that
// block generates, imported from its file by a path relative to this
// one. Both files are placed by their blocks' `out` directives, each
// relative to the file declaring the block.

// outDirective names where a target block's output goes; tdl reads it, and
// a dependency's reaches its import.
const outDirective = "out"

// imported is one type an extern brings in.
type imported struct {
	module, name string
	at           *ir.Position
}

// externType is the TypeScript name of an extern, recording its import.
func (g *generator) externType(r *emit.Ref) (string, error) {
	own := r.Extern.GetDirectives()
	if f, ok := g.Find(own, "foreign"); ok {
		args := f.GetArgs()
		if len(args) != 2 {
			return "", emit.Unsupported(f.GetPosition(),
				"foreign takes a module and a type name, and %d argument(s) were given", len(args))
		}
		return g.importType(r, args[0].GetText(), args[1].GetText(), f.GetPosition())
	}
	if g.mapped {
		module, err := g.sourceModule(r)
		if err != nil {
			return "", err
		}
		return g.importType(r, module, g.externName(r), r.Pos)
	}

	for _, dep := range g.Model.GetImports() {
		if dep.GetPackage() != r.Extern.GetPackage() {
			continue
		}
		// A block holding only declaration directives reaches the
		// extern alone.
		if len(plugin.Directives(g.Target, dep.GetDirectives())) == 0 &&
			len(plugin.Directives(g.Target, own)) == 0 {
			break
		}
		module, err := g.dependencyModule(r, dep)
		if err != nil {
			return "", err
		}
		return g.importType(r, module, g.externName(r), r.Pos)
	}
	return "", emit.Unsupported(r.Pos,
		"%s is declared in another package with no typescript target block, and no foreign directive maps it", r.Name)
}

// externName is the name an extern is imported as: the type its foreign
// directive names, or else the one its dependency's block generates.
func (g *generator) externName(r *emit.Ref) string {
	own := r.Extern.GetDirectives()
	if f, ok := g.Find(own, "foreign"); ok && len(f.GetArgs()) == 2 {
		return f.GetArgs()[1].GetText()
	}
	if name, ok := g.Text(own, "name"); ok {
		return name
	}
	return emit.Pascal(emit.LastSegment(r.Extern.GetName()))
}

// dependencyModule is the specifier this file imports a dependency's
// generated file by.
func (g *generator) dependencyModule(r *emit.Ref, dep *ir.Import) (string, error) {
	depOut, ok := g.Find(dep.GetDirectives(), outDirective)
	if !ok || len(depOut.GetArgs()) == 0 {
		return "", emit.Unsupported(r.Pos,
			"%s is generated by a typescript target block with no out directive, so this file cannot import it by a relative path", r.Name)
	}
	rootOut, ok := g.Block(outDirective)
	if !ok || len(rootOut.GetArgs()) == 0 {
		return "", emit.Unsupported(r.Pos,
			"%s is generated into a dependency's out directory, and this target block has no out directive to import it from", r.Name)
	}
	from := placed(rootOut)
	to := placed(depOut)
	rel, err := filepath.Rel(from, to)
	if err != nil {
		return "", emit.Unsupported(r.Pos, "%s is generated in %s, which has no path relative to %s", r.Name, to, from)
	}
	file := defaultFile
	if pkg := dep.GetPackage(); pkg != "" {
		file = emit.LastSegment(pkg)
	}
	spec := path.Join(filepath.ToSlash(rel), file+".js")
	if !strings.HasPrefix(spec, "../") {
		spec = "./" + spec
	}
	return spec, nil
}

// sourceModule is the specifier a mapped module imports an extern by: the
// .tdl file declaring it, by the path this file imports it with, which
// tsc sends back through the mapper.
func (g *generator) sourceModule(r *emit.Ref) (string, error) {
	var paths []string
	for _, dep := range g.Model.GetImports() {
		if dep.GetPackage() == r.Extern.GetPackage() && !slices.Contains(paths, dep.GetPath()) {
			paths = append(paths, dep.GetPath())
		}
	}
	switch len(paths) {
	case 0:
		return "", emit.Unsupported(r.Pos, "%s is declared in package %s, which this file does not import", r.Name, r.Extern.GetPackage())
	case 1:
	default:
		return "", emit.Unsupported(r.Pos, "%s is declared in package %s, which %s all declare, so the module it comes from is unknown",
			r.Name, r.Extern.GetPackage(), strings.Join(paths, ", "))
	}
	spec := path.Clean(filepath.ToSlash(paths[0]))
	if !strings.HasPrefix(spec, "../") && !strings.HasPrefix(spec, "/") {
		spec = "./" + spec
	}
	return spec, nil
}

// placed is the directory an out directive names, relative to the file
// declaring its block. The caller has checked it has an argument.
func placed(out *ir.Directive) string {
	dir := out.GetArgs()[0].GetText()
	if filepath.IsAbs(dir) {
		return filepath.Clean(dir)
	}
	return filepath.Join(filepath.Dir(out.GetPosition().GetFilename()), dir)
}

// importType records an import of name from module for the declaration
// being rendered. Whether it collides with another declaration's import
// or with a declared name waits for [generator.importConflicts], when the
// emitted declarations are known.
func (g *generator) importType(r *emit.Ref, module, name string, at *ir.Position) (string, error) {
	if at == nil {
		at = r.Pos
	}
	if module == "" {
		return "", emit.Unsupported(at, "the foreign mapping of %s has no module", r.Name)
	}
	if !ident.MatchString(name) || reserved[name] {
		return "", emit.Unsupported(at, "%s is mapped to %q, which cannot name a TypeScript type", r.Name, name)
	}
	if have, ok := g.uses[name]; ok && have.module != module {
		return "", emit.Unsupported(at, "%s would import %s from %s, and %s already names the one from %s",
			r.Name, name, module, name, have.module)
	}
	g.uses[name] = imported{module: module, name: name, at: at}
	return name, nil
}

// importConflicts skips each declaration, in source order, importing a
// name that an emitted declaration declares or an earlier declaration
// imports from another module. It reports whether it skipped any, since
// the cascade then runs again.
func (g *generator) importConflicts(own []*ir.Decl, skipped map[*ir.Decl]bool, uses map[*ir.Decl]map[string]imported) bool {
	declared := map[string]string{}
	for _, d := range own {
		if !skipped[d] {
			for _, n := range g.declares[d] {
				declared[n] = d.GetMeta().GetName()
			}
		}
	}

	skippedAny := false
	taken := map[string]imported{}
	for _, d := range own {
		if skipped[d] {
			continue
		}
		if err := conflict(d.GetMeta().GetName(), uses[d], declared, taken); err != nil {
			g.Skip(err)
			skipped[d] = true
			skippedAny = true
			continue
		}
		maps.Copy(taken, uses[d])
	}
	return skippedAny
}

// conflict is why one declaration's imports cannot be written, or nil.
func conflict(decl string, uses map[string]imported, declared map[string]string, taken map[string]imported) error {
	for _, name := range slices.Sorted(maps.Keys(uses)) {
		im := uses[name]
		if other, ok := declared[name]; ok {
			return emit.Unsupported(im.at, "%s would import %s, which %s declares", decl, name, other)
		}
		if have, ok := taken[name]; ok && have.module != im.module {
			return emit.Unsupported(im.at, "%s would import %s from %s, and %s already names the one from %s",
				decl, name, im.module, name, have.module)
		}
	}
	return nil
}

// importLines writes an `import type` per module, names sorted, for the
// imports the emitted declarations use.
func importLines(imports map[string]imported) string {
	byModule := map[string][]string{}
	for _, im := range imports {
		byModule[im.module] = append(byModule[im.module], im.name)
	}
	modules := make([]string, 0, len(byModule))
	for m := range byModule {
		modules = append(modules, m)
	}
	slices.Sort(modules)

	var b strings.Builder
	for _, m := range modules {
		names := byModule[m]
		slices.Sort(names)
		b.WriteString("import type { " + strings.Join(names, ", ") + " } from " + strconv.Quote(m) + ";\n")
	}
	return b.String()
}
