// Package openapi generates an OpenAPI document from a resolved model.
//
// docs/design/schema-backends.md has the mapping and the reasons for it.
// The document holds schemas and no paths: every declaration is a schema
// under components (definitions in 2.0), built by
// backend/internal/jsonschema in the dialect the version speaks. An enum
// whose variants carry fields is a oneOf of one schema per variant with a
// discriminator naming them, which OpenAPI 2.0 has no way to say.
package openapi

import (
	"bytes"
	"context"

	"github.com/unstoppablemango/tdl/backend/internal/emit"
	"github.com/unstoppablemango/tdl/backend/internal/jsonschema"
	"github.com/unstoppablemango/tdl/ir"
	"github.com/unstoppablemango/tdl/plugin"
)

// Name is what this backend is called, in a target block and as
// tdl-gen-openapi on PATH.
const Name = "openapi"

// Backend implements [plugin.Backend].
type Backend struct{}

func (Backend) Describe() plugin.Description {
	str := []ir.LiteralKind{ir.LiteralKind_LITERAL_KIND_STRING}
	return plugin.Description{
		Name:    Name,
		Version: "0.1.0",
		// Each request is answered from the request alone.
		Reuse: true,
		Directives: []*plugin.DirectiveSpec{
			// The schema's name for a type or a variant, or a field's
			// property name.
			{Name: "name", MinArgs: 1, MaxArgs: 1, ArgKinds: str},
			// The property a fielded enum's variants are told apart by.
			// Written on the target block it is the default, and on an enum
			// it wins.
			{Name: "discriminant", MinArgs: 1, MaxArgs: 1, ArgKinds: str},
			// Refuses properties a struct or variant does not declare. On the
			// target block it applies to every one.
			{Name: "closed"},
			// The OpenAPI version: "3.1", the default, "3.0", or "2.0".
			{Name: "openapi", MinArgs: 1, MaxArgs: 1, ArgKinds: str},
			// The file format: "yaml", the default, or "json".
			{Name: "format", MinArgs: 1, MaxArgs: 1, ArgKinds: str},
			// The document's info.title and info.version.
			{Name: "title", MinArgs: 1, MaxArgs: 1, ArgKinds: str},
			{Name: "version", MinArgs: 1, MaxArgs: 1, ArgKinds: str},
		},
	}
}

// version is an OpenAPI version this backend writes: the field and value
// that say which, and the dialect its schemas are written in.
type version struct {
	key, value string
	dialect    jsonschema.Dialect
}

const components = "#/components/schemas/"

var versions = map[string]version{
	// A 3.1 schema is JSON Schema 2020-12.
	"3.1": {key: "openapi", value: "3.1.1", dialect: jsonschema.Dialect{
		Name: "OpenAPI 3.1", Ref: components, Siblings: true, Deprecated: true, Const: true,
		ContentEncoding: true, PropertyNames: true, Unions: jsonschema.UnionsReferenced, Formats: true,
	}},
	// A 3.0 schema ignores a $ref's siblings, has no const, and says null
	// with `nullable`.
	"3.0": {key: "openapi", value: "3.0.4", dialect: jsonschema.Dialect{
		Name: "OpenAPI 3.0", Ref: components, Deprecated: true, Null: jsonschema.NullNullable,
		Unions: jsonschema.UnionsReferenced, Formats: true,
	}},
	// A 2.0 schema has no oneOf and no null.
	"2.0": {key: "swagger", value: "2.0", dialect: jsonschema.Dialect{
		Name: "OpenAPI 2.0", Ref: "#/definitions/", Null: jsonschema.NullExtension,
		Unions: jsonschema.UnionsNone, Formats: true,
	}},
}

const defaultVersion = "3.1"

const generated = "Code generated by tdl. DO NOT EDIT."

// Generate returns one document holding every declaration the model owns.
func (Backend) Generate(_ context.Context, req *plugin.Request) (*plugin.Response, error) {
	s := emit.NewSession(req, "OpenAPI")
	v := versions[defaultVersion]
	if d, ok := s.Block("openapi"); ok {
		known, ok := versions[d.GetArgs()[0].GetText()]
		if !ok {
			s.Error(d.GetPosition(), "%q is not an OpenAPI version this backend writes; use \"3.1\", \"3.0\", or \"2.0\"", d.GetArgs()[0].GetText())
			return s.Response(nil), nil
		}
		v = known
	}
	yaml := true
	if d, ok := s.Block("format"); ok {
		switch d.GetArgs()[0].GetText() {
		case "yaml":
		case "json":
			yaml = false
		default:
			s.Error(d.GetPosition(), "%q is not a format this backend writes; use \"yaml\" or \"json\"", d.GetArgs()[0].GetText())
			return s.Response(nil), nil
		}
	}

	schemas, _ := jsonschema.New(s, v.dialect).Build(s.Own())
	if schemas.Len() == 0 {
		return s.Response(nil), nil
	}
	if !v.dialect.Siblings {
		jsonschema.Hoist(schemas)
	}

	pkg := req.GetModel().GetPackage()
	title, ver := "model", "0.0.0"
	if pkg != "" {
		title = pkg
	}
	if t, ok := s.Block("title"); ok {
		title = t.GetArgs()[0].GetText()
	}
	if t, ok := s.Block("version"); ok {
		ver = t.GetArgs()[0].GetText()
	}

	doc := jsonschema.NewObject().Set(v.key, v.value)
	if !yaml {
		// JSON has no comments, and an extension is what OpenAPI allows
		// beside its own fields.
		doc.Set("x-generated", generated)
	}
	doc.Set("info", jsonschema.NewObject().Set("title", title).Set("version", ver))
	doc.Set("paths", jsonschema.NewObject())
	if v.key == "swagger" {
		doc.Set("definitions", schemas)
	} else {
		doc.Set("components", jsonschema.NewObject().Set("schemas", schemas))
	}

	var buf bytes.Buffer
	ext := ".openapi.json"
	if yaml {
		ext = ".openapi.yaml"
		buf.WriteString("# " + generated + "\n")
		writeYAML(&buf, doc)
	} else {
		jsonschema.WriteJSON(&buf, doc)
		buf.WriteString("\n")
	}

	path := "model" + ext
	if pkg != "" {
		path = emit.LastSegment(pkg) + ext
	}
	return s.Response([]*plugin.File{{Path: path, Content: buf.Bytes()}}), nil
}
