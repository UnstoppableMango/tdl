// Generating warns about each fact the Smithy loses. Under a `roundtrip`
// directive, a declaration whose shapes do not read back as it carries
// itself whole as TDL in a tdl#source trait, and what no shape carries,
// such as the package and the declarations Smithy has no form for, goes
// in the tdl metadata.

// traitFile is the file defining the tdl#source trait, written beside the
// model when a shape uses it.
const traitFile = "tdl.smithy"

const traitDefinition = `// Code generated by tdl. DO NOT EDIT.

$version: "2"

namespace tdl

/// The declaration as TDL.
@trait
string source
`

// quote is a Smithy string literal: JSON's, without its HTML escaping.
func quote(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

// carry sets the tdl#source of each declaration whose shapes do not read
// back as it. A declaration carrying itself changes what the shapes
// naming it read as, so it repeats until none changes.
func (g *generator) carry(kept []rendered, shapes []*shape) {
	want := map[string]string{}
	for _, it := range g.Items() {
		if it.GetName() != "" {
			want[it.GetName()] = it.GetSource()
		}
	}
	at := map[string]ast.Position{}
	for i, s := range shapes {
		at[s.id] = ast.Position{Line: i + 1}
	}
	for changed := true; changed; {
		changed = false
		r := &reader{}
		r.Roundtrip = true
		if err := r.prepare(shapes, at, g.ns); err != nil {
			return
		}
		for _, k := range kept {
			s := k.shapes[0]
			if s.traits.source != nil {
				continue
			}
			name := k.decl.GetMeta().GetName()
			mark := len(r.Diags)
			decl := r.shape(s)
			if decl != nil && len(r.Diags) == mark && emit.PrintItem(decl) == want[name] {
				continue
			}
			src := want[name]
			s.traits.source = &src
			changed = true
		}
	}
}

// metadata is the tdl metadata statement: the package when the namespace
// does not say it, or no shape does, the package's doc comment, the imports, and every
// top-level item not emitted, by its index. Roundtrip always writes it,
// since it is how import knows to infer no directives.
func (g *generator) metadata(emitted map[string]bool, shapes bool) string {
	var a annotations
	if pkg := g.Model.GetPackage(); pkg != g.ns || !shapes {
		a.Package = &pkg
	}
	if doc := g.Model.GetDoc(); len(doc) > 0 {
		s := strings.Join(doc, "\n")
		a.Doc = &s
	}
	a.Import = g.Imports()
	for _, it := range g.Carried(emitted) {
		a.Item = append(a.Item, fmt.Sprintf("%d %s", it.At, it.Source))
	}

	var b strings.Builder
	fmt.Fprintf(&b, "metadata %s = {\n", metadataKey)
	if a.Package != nil {
		fmt.Fprintf(&b, "    package: %s\n", quote(*a.Package))
	}
	if a.Doc != nil {
		fmt.Fprintf(&b, "    doc: %s\n", quote(*a.Doc))
	}
	for _, list := range []struct {
		key    string
		values []string
	}{{"import", a.Import}, {"item", a.Item}} {
		if len(list.values) == 0 {
			continue
		}
		fmt.Fprintf(&b, "    %s: [\n", list.key)
		for _, v := range list.values {
			fmt.Fprintf(&b, "        %s\n", quote(v))
		}
		b.WriteString("    ]\n")
	}
	b.WriteString("}\n")
	return b.String()
}

// losses warns about what a declaration loses, written as shape s.
func (g *generator) losses(d *ir.Decl, s *shape) {
	written := s.name()
	name, pos := d.GetMeta().GetName(), d.GetMeta().GetPosition()
	if written != name {
		g.Lose(emit.LossName, pos, "%s is written %s, which reads back as its name", name, written)
	} else {
		g.CheckRenamed(d.GetDirectives(), emit.Pascal(written) != written, "%s", name)
	}
	g.docLoss(d.GetMeta())

	if d.GetStructure() != nil {
		g.LoseKind(d)
		g.fieldLosses(name, d.Fields())
	}
	g.LoseConforms(d, "Smithy")

	if e := d.GetEnumeration(); e != nil {
		for _, v := range e.GetVariants() {
			g.variantLosses(written, name, emit.Fielded(e), v)
		}
	}
	if nt := d.GetNewtype(); nt != nil {
		g.typeLosses(nt.GetBase(), nil)
		g.sugarLoss(d, s)
	}
}

// sugarLoss warns about a newtype over a collection whose shape import
// reads as the collection a member needs.
func (g *generator) sugarLoss(d *ir.Decl, s *shape) {
	if len(emit.Doc(d.GetMeta())) > 0 || d.GetMeta().GetDeprecated() != nil {
		return
	}
	r := &reader{ns: g.ns}
	if r.collection(s) {
		g.Lose(emit.LossNewtype, d.GetMeta().GetPosition(), "newtype %s is written as the shape a member holding its base would use, and reads back as its base", d.GetMeta().GetName())
	}
}

// variantLosses warns about what an enum variant loses, as an enum member
// or a union member.
func (g *generator) variantLosses(shapeName, owner string, fielded bool, v *ir.Variant) {
	vname, pos := v.GetMeta().GetName(), v.GetMeta().GetPosition()
	what := owner + "." + vname
	g.docLoss(v.GetMeta())
	if !fielded {
		written := g.VariantName(v, emit.ScreamingSnake)
		g.CheckRenamed(v.GetDirectives(), emit.ScreamingSnake(vname) != written, "%s", what)
		return
	}
	if back := emit.Pascal(emit.Camel(vname)); back != vname {
		g.Lose(emit.LossName, pos, "%s is written as member %s, which reads back as %s", what, emit.Camel(vname), back)
	}
	if len(v.GetFields()) == 0 {
		if d, ok := g.Find(v.GetDirectives(), "name"); ok {
			g.Lose(emit.LossName, d.GetPosition(), "%s carries no fields, so its name directive names no structure and does not read back", what)
		}
		return
	}
	structure := g.variantShape(shapeName, v)
	g.CheckRenamed(v.GetDirectives(), structure != shapeName+emit.Pascal(vname), "%s", what)
	g.fieldLosses(what, v.GetFields())
}

// fieldLosses warns about what a structure's members lose.
func (g *generator) fieldLosses(owner string, fields []*ir.Field) {
	includes := unlower.Includes(g.Model, fields)
	for i, inc := range includes {
		if inc != "" && (i == 0 || includes[i-1] != inc) {
			g.Lose(emit.LossInclude, fields[i].GetMeta().GetPosition(), "%s's include of %s is flattened into its members", owner, inc)
		}
	}
	for _, f := range fields {
		name, pos := f.GetMeta().GetName(), f.GetMeta().GetPosition()
		if written := g.FieldName(f, asWritten); written != name {
			g.Lose(emit.LossName, pos, "%s.%s is written %s, which reads back as its name", owner, name, written)
		} else {
			g.CheckRenamed(f.GetDirectives(), false, "%s.%s", owner, name)
		}
		if f.GetOwned() {
			g.Lose(emit.LossOwned, pos, "%s.%s is owned, which Smithy does not carry", owner, name)
		}
		if f.GetDefaultValue() != nil {
			g.Lose(emit.LossDefault, pos, "%s.%s has a default, which is not written", owner, name)
		}
		g.docLoss(f.GetMeta())
		g.typeLosses(f.GetType(), pos)
	}
}

// docLoss warns when a node's doc comment does not read back: a line's
// trailing whitespace is not written.
func (g *generator) docLoss(m *ir.Meta) {
	if !slices.Equal(emit.Doc(m), m.GetDoc()) {
		g.Lose(emit.LossDoc, m.GetPosition(), "%s's doc comment loses trailing whitespace", m.GetName())
	}
}

// typeLosses warns about what a type loses in Smithy: a primitive's kind,
// sugar import writes another way, and absence import reads another way.
// A newtype or alias it names warns where it is declared.
func (g *generator) typeLosses(id *ir.ID, at *ir.Position) {
	t := g.Model.Type(id)
	if t == nil || t.GetParam() != nil || t.GetUnit() != nil {
		return
	}
	pos := cmp.Or(at, t.GetPosition())
	decl := g.Model.Decl(t.GetCtor())
	if decl == nil || decl.GetPrimitive() == nil && decl.GetEnumeration() == nil {
		return
	}
	name, wrote := decl.GetMeta().GetName(), t.GetWrote()
	switch {
	case decl.GetEnumeration() != nil:
		switch {
		case name == "Option" && wrote == ir.SyntacticForm_SYNTACTIC_FORM_QUESTION:
		case name == "Option" || name == "Nullable":
			g.Lose(emit.LossOptional, pos, "%s reads back as T?", name)
		default:
			return
		}
	case name == "List" && wrote != ir.SyntacticForm_SYNTACTIC_FORM_BRACKETS,
		name == "Set" && wrote != ir.SyntacticForm_SYNTACTIC_FORM_BRACES,
		name == "Map" && wrote != ir.SyntacticForm_SYNTACTIC_FORM_ARROW:
		g.Lose(emit.LossCollection, pos, "%s reads back written as sugar", name)
	case preludeShapes[name] != "" && primitives[preludeShapes[name]] != name:
		g.Lose(emit.LossPrimitive, pos, "%s is a Smithy %s, which reads back as %s", name, preludeShapes[name], primitives[preludeShapes[name]])
	}
	for _, arg := range t.GetArgs() {
		g.typeLosses(arg, at)
	}
}
