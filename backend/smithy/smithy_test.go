func TestDocsAndDeprecation(t *testing.T) {
	b := irtest.New("shop")
	old := irtest.Field("fax", b.Named("string"))
	old.Meta.Deprecated = &ir.Deprecation{Reason: "nobody has one"}
	b.Own(&ir.Decl{
		Meta: &ir.Meta{Name: "Contact", Doc: []string{"How to reach someone."}, Deprecated: &ir.Deprecation{}},
		Node: &ir.Decl_Structure{Structure: &ir.Struct{Fields: []*ir.Field{old}}},
	})

	contains(t, check(t, generate(t, b)),
		"/// How to reach someone. @deprecated structure Contact {",
		`@required @deprecated(message: "nobody has one") fax: String`,
	)
}

func TestNamespace(t *testing.T) {
	b := irtest.New("shop")
	b.Own(value("Note", irtest.Field("body", b.Named("string"))))
	b.Model.Targets = []*ir.TargetBlock{{
		Meta:       &ir.Meta{Name: smithy.Name},
		Directives: []*ir.Directive{{Name: "package", Target: smithy.Name, Args: []*ir.Literal{irtest.Text("acme.billing")}}},
	}}
	resp := generate(t, b)
	contains(t, check(t, resp), "namespace acme.billing")

	// A Smithy file has to have a namespace.
	b.Model.Targets = nil
	b.Model.Package = ""
	resp = generate(t, b)
	if len(resp.GetFiles()) != 0 || len(resp.GetDiagnostics()) != 1 ||
		resp.GetDiagnostics()[0].GetSeverity() != plugin.Severity_SEVERITY_ERROR {
		t.Errorf("no namespace should be an error and nothing else: %+v", resp)
	}
}

// Every case in the conformance corpus, and the smoke fixture, generates
// something Smithy accepts, whatever this backend warned about.
func TestConformance(t *testing.T) {
	corpus := filepath.Join("..", "..", "testdata", "conformance")
	dirs := []string{filepath.Join("..", "..", "testdata", "gen", "smoke")}
	for _, c := range []string{
		"aliases", "collections", "comments", "constraints", "deprecated", "entity",
		"enum_variants", "mixin_include", "newtype", "targets", "targets_variants", "value",
	} {
		dirs = append(dirs, filepath.Join(corpus, c))
	}

	for _, dir := range dirs {
		t.Run(filepath.Base(dir), func(t *testing.T) {
			model := irtest.Conformance(t, dir)
			resp, err := smithy.Backend{}.Generate(context.Background(), &plugin.Request{Target: smithy.Name, Model: model})
			if err != nil {
				t.Fatal(err)
			}
			for _, d := range resp.GetDiagnostics() {
				if d.GetSeverity() == plugin.Severity_SEVERITY_ERROR {
					t.Errorf("error: %s", d.GetMessage())
				}
			}
			if len(resp.GetFiles()) > 0 {
				check(t, resp)
			}
		})
	}
}
