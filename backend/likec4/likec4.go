// Package likec4 generates LikeC4 source from a resolved model, so a model
// renders as an architecture diagram. The mapping is in
// docs/design/likec4-backend.md.
package likec4

import (
	"context"
	"fmt"
	"strings"

	"github.com/unstoppablemango/tdl/backend/internal/emit"
	"github.com/unstoppablemango/tdl/ir"
	"github.com/unstoppablemango/tdl/plugin"
)

// Name names this backend in a target block and as tdl-gen-likec4.
const Name = "likec4"

// Backend implements [plugin.Backend].
type Backend struct{}

func (Backend) Describe() plugin.Description {
	return plugin.Description{
		Name:    Name,
		Version: "0.1.0",
		// Each request stands alone.
		Reuse: true,
	}
}

const header = "// Code generated by tdl. DO NOT EDIT.\n"

// specification is tdl.c4: the element and relationship kinds every model
// uses. It is the same bytes for every model, so several packages generated
// into one project declare each kind once.
const specification = header + `
specification {
  element package {
    style {
      shape rectangle
    }
  }
  element entity {
    style {
      shape cylinder
    }
  }
  element value {
    style {
      shape rectangle
    }
  }
  element mixin {
    style {
      shape rectangle
      border dashed
    }
  }
  element enum {
    style {
      shape rectangle
    }
  }
  element newtype {
    style {
      shape rectangle
    }
  }
  element class {
    style {
      shape rectangle
      border dashed
    }
  }
  element service {
    style {
      shape component
    }
  }

  relationship references
  relationship composes
  relationship includes
  relationship conforms
  relationship accepts
  relationship returns
}
`

// SpecFile is the file holding the specification.
const SpecFile = "tdl.c4"

type generator struct {
	*emit.Session
}

// Generate returns tdl.c4 and one <package id>.c4 holding the package
// element and an element per declaration.
func (Backend) Generate(_ context.Context, req *plugin.Request) (*plugin.Response, error) {
	g := &generator{Session: emit.NewSession(req, "LikeC4")}

	pkg := g.Model.GetPackage()
	id, title := packageID(pkg), pkg
	if pkg == "" {
		title = id
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\nmodel {\n")
	fmt.Fprintf(&b, "  package %s %s {\n", id, quote(title))
	first := true
	for _, d := range g.Own() {
		kind, ok := elementKind(d)
		if !ok {
			continue
		}
		if !first {
			b.WriteString("\n")
		}
		first = false
		g.element(&b, d, kind)
	}
	b.WriteString("  }\n}\n")

	return g.Response([]*plugin.File{
		{Path: SpecFile, Content: []byte(specification)},
		{Path: id + ".c4", Content: []byte(b.String())},
	}), nil
}

// packageID joins a package's segments with _, since packages are flat
// elements; a model with no package is "model".
func packageID(pkg string) string {
	if pkg == "" {
		return "model"
	}
	return strings.ReplaceAll(pkg, ".", "_")
}

// elementKind is the specification's kind for a declaration, or false for
// one with no element: an alias, a primitive, or a unit.
func elementKind(d *ir.Decl) (string, bool) {
	switch {
	case d.GetStructure() != nil:
		switch d.GetStructure().GetKind() {
		case ir.StructKind_STRUCT_KIND_ENTITY:
			return "entity", true
		case ir.StructKind_STRUCT_KIND_MIXIN:
			return "mixin", true
		}
		return "value", true
	case d.GetEnumeration() != nil:
		return "enum", true
	case d.GetNewtype() != nil:
		return "newtype", true
	case d.GetClass() != nil:
		return "class", true
	}
	return "", false
}

func (g *generator) element(b *strings.Builder, d *ir.Decl, kind string) {
	name := emit.LastSegment(d.GetMeta().GetName())
	fmt.Fprintf(b, "    %s %s %s {\n", kind, name, quote(name))
	if desc := g.description(d); desc != "" {
		fmt.Fprintf(b, "      description %s\n", markdown(desc, "      "))
	}
	if tech := g.technology(d); tech != "" {
		fmt.Fprintf(b, "      technology %s\n", quote(tech))
	}
	b.WriteString("    }\n")
}

// technology is a newtype's base, or a generic declaration's signature.
func (g *generator) technology(d *ir.Decl) string {
	if nt := d.GetNewtype(); nt != nil {
		return g.spell(nt.GetBase())
	}
	params := d.Params()
	if len(params) == 0 {
		return ""
	}
	names := make([]string, len(params))
	for i, p := range params {
		names[i] = p.GetName()
	}
	return emit.LastSegment(d.GetMeta().GetName()) + "<" + strings.Join(names, ", ") + ">"
}

// description is markdown: the doc comment, the deprecation, and one line
// per field or variant, written as the source would write it.
func (g *generator) description(d *ir.Decl) string {
	var paras []string
	if doc := emit.Doc(d.GetMeta()); len(doc) > 0 {
		paras = append(paras, strings.Join(doc, "\n"))
	}
	if reason, ok := emit.Deprecated(d.GetMeta()); ok {
		line := "**Deprecated.**"
		if reason != "" {
			line = "**Deprecated:** " + reason
		}
		paras = append(paras, line)
	}

	var members []string
	included := map[string]bool{}
	for _, f := range d.Fields() {
		if from := f.GetIncludedFrom(); from != nil {
			if !included[from.GetName()] {
				included[from.GetName()] = true
				members = append(members, "- include "+from.GetName())
			}
			continue
		}
		members = append(members, "- "+g.field(f))
	}
	for _, v := range d.GetEnumeration().GetVariants() {
		members = append(members, "- "+g.variant(v))
	}
	if len(members) > 0 {
		paras = append(paras, strings.Join(members, "\n"))
	}
	return strings.Join(paras, "\n\n")
}

func (g *generator) field(f *ir.Field) string {
	s := deprecated(f.GetMeta())
	if f.GetOwned() {
		s += "owned "
	}
	s += f.GetMeta().GetName() + ": " + g.spell(f.GetType())
	if cs := f.GetConstraints(); len(cs) > 0 {
		texts := make([]string, len(cs))
		for i, c := range cs {
			texts[i] = constraint(c)
		}
		s += " where " + strings.Join(texts, " ")
	}
	if def := f.GetDefaultValue(); def != nil {
		s += " = " + literal(def)
	}
	return s
}

func (g *generator) variant(v *ir.Variant) string {
	s := deprecated(v.GetMeta()) + v.GetMeta().GetName()
	if len(v.GetFields()) == 0 {
		return s
	}
	fields := make([]string, len(v.GetFields()))
	for i, f := range v.GetFields() {
		fields[i] = g.field(f)
	}
	return s + " { " + strings.Join(fields, " ") + " }"
}

// deprecated is a member's deprecation as the source writes it, with a
// trailing space, or "" for a member that is not deprecated.
func deprecated(m *ir.Meta) string {
	reason, ok := emit.Deprecated(m)
	switch {
	case !ok:
		return ""
	case reason == "":
		return "deprecated "
	}
	return fmt.Sprintf("deprecated(%q) ", reason)
}

// spell writes a type in TDL spelling, in the form the source wrote it.
func (g *generator) spell(id *ir.ID) string {
	if !id.Resolved() {
		return "?"
	}
	t := g.Model.Type(id)
	if t == nil {
		return "?"
	}
	args := make([]string, len(t.GetArgs()))
	for i, a := range t.GetArgs() {
		args[i] = g.spell(a)
	}

	switch {
	case t.GetParam() != nil:
		return t.GetParam().GetName() + generic(args)
	case t.GetExtern() != nil:
		return t.GetExtern().GetName() + generic(args)
	case t.GetUnit() != nil:
		if u := g.Model.Unit(t.GetUnit()); u.GetWrote() != "" {
			return u.GetWrote()
		}
		return "?"
	}

	switch t.GetWrote() {
	case ir.SyntacticForm_SYNTACTIC_FORM_BRACKETS:
		if len(args) == 1 {
			return "[" + args[0] + "]"
		}
	case ir.SyntacticForm_SYNTACTIC_FORM_BRACES:
		if len(args) == 1 {
			return "{" + args[0] + "}"
		}
	case ir.SyntacticForm_SYNTACTIC_FORM_ARROW:
		if len(args) == 2 {
			return "{" + args[0] + " -> " + args[1] + "}"
		}
	case ir.SyntacticForm_SYNTACTIC_FORM_QUESTION:
		if len(args) == 1 {
			return args[0] + "?"
		}
	case ir.SyntacticForm_SYNTACTIC_FORM_OR_NULL:
		if len(args) == 1 {
			return args[0] + " | null"
		}
	}
	return emit.LastSegment(t.GetCtor().GetName()) + generic(args)
}

func generic(args []string) string {
	if len(args) == 0 {
		return ""
	}
	return "<" + strings.Join(args, ", ") + ">"
}

func constraint(c *ir.Constraint) string {
	if len(c.GetArgs()) == 0 {
		return c.GetName()
	}
	args := make([]string, len(c.GetArgs()))
	for i, a := range c.GetArgs() {
		args[i] = literal(a)
	}
	return c.GetName() + "(" + strings.Join(args, ", ") + ")"
}

// literal writes a literal as TDL source writes it.
func literal(l *ir.Literal) string {
	switch l.GetKind() {
	case ir.LiteralKind_LITERAL_KIND_STRING:
		return fmt.Sprintf("%q", l.GetText())
	case ir.LiteralKind_LITERAL_KIND_REGEX:
		return "/" + l.GetText() + "/"
	case ir.LiteralKind_LITERAL_KIND_LIST:
		items := make([]string, len(l.GetItems()))
		for i, item := range l.GetItems() {
			items[i] = literal(item)
		}
		return "[" + strings.Join(items, ", ") + "]"
	case ir.LiteralKind_LITERAL_KIND_RANGE:
		var lo, hi string
		if r := l.GetRange(); r.Low != nil {
			lo = fmt.Sprint(r.GetLow())
		}
		if r := l.GetRange(); r.High != nil {
			hi = fmt.Sprint(r.GetHigh())
		}
		return lo + ".." + hi
	}
	return l.GetText()
}

// quote writes a single-quoted LikeC4 string.
func quote(s string) string {
	return "'" + escape(s) + "'"
}

// markdown writes a triple-quoted LikeC4 string, its lines indented to sit
// under the property naming it.
func markdown(s, indent string) string {
	var b strings.Builder
	b.WriteString("'''\n")
	for line := range strings.SplitSeq(escape(s), "\n") {
		if line != "" {
			b.WriteString(indent + "  " + line)
		}
		b.WriteString("\n")
	}
	b.WriteString(indent + "'''")
	return b.String()
}

func escape(s string) string {
	return strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s)
}
