var element = regexp.MustCompile(`(?m)^    (entity|value|mixin|enum|newtype|class) (\w+) '`)

// The smoke fixture and every conformance case generate an element for
// each of their own declarations other than aliases and units.
func TestConformance(t *testing.T) {
	corpus := filepath.Join("..", "..", "testdata", "conformance")
	dirs := []string{filepath.Join("..", "..", "testdata", "gen", "smoke")}
	for _, c := range []string{
		"aliases", "classes", "collections", "comments", "constraints", "deprecated", "entity",
		"enum_variants", "mixin_include", "newtype", "parameters", "targets", "targets_variants",
		"units", "value",
	} {
		dirs = append(dirs, filepath.Join(corpus, c))
	}

	for _, dir := range dirs {
		t.Run(filepath.Base(dir), func(t *testing.T) {
			m := irtest.Conformance(t, dir)
			resp := generate(t, m)
			for _, d := range resp.GetDiagnostics() {
				t.Errorf("diagnostic: %s", d.GetMessage())
			}
			_, src := model(t, resp)

			want := map[string]bool{}
			for _, d := range m.GetDecls() {
				if d.GetMeta().GetPosition().GetFilename() == prelude.Name {
					continue
				}
				if d.GetAlias() != nil || d.GetUnit() != nil || d.GetPrimitive() != nil {
					continue
				}
				want[d.GetMeta().GetName()] = true
			}
			got := map[string]int{}
			for _, match := range element.FindAllStringSubmatch(src, -1) {
				got[match[2]]++
			}
			for name := range want {
				if got[name] != 1 {
					t.Errorf("%s has %d elements, want 1", name, got[name])
				}
			}
			for name := range got {
				if !want[name] {
					t.Errorf("%s has an element and is not one of the model's declarations", name)
				}
			}
		})
	}
}
