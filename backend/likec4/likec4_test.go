func generate(t *testing.T, m *ir.Model) *plugin.Response {
	t.Helper()
	resp, err := likec4.Backend{}.Generate(context.Background(), &plugin.Request{
		Target: likec4.Name,
		Model:  m,
	})
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	return resp
}

// model returns the response's model file, the one beside tdl.c4, and
// validates the pair when the likec4 CLI is on PATH.
func model(t *testing.T, resp *plugin.Response) (string, string) {
	t.Helper()
	files := resp.GetFiles()
	if len(files) != 2 || files[0].GetPath() != likec4.SpecFile {
		t.Fatalf("files = %v, diagnostics = %+v", files, resp.GetDiagnostics())
	}
	validate(t, files)
	return files[1].GetPath(), string(files[1].GetContent())
}

// validate runs `likec4 validate` over the files as one project. Without
// the CLI these tests check substrings only.
func validate(t *testing.T, files []*plugin.File) {
	t.Helper()
	cli, err := exec.LookPath("likec4")
	if err != nil {
		return
	}
	dir := t.TempDir()
	for _, f := range files {
		if err := os.WriteFile(filepath.Join(dir, f.GetPath()), f.GetContent(), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	cmd := exec.Command(cli, "validate", "--no-layout", dir)
	cmd.Env = append(os.Environ(), "HOME="+dir)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Errorf("likec4 rejects the output: %v\n%s\n%s", err, out, files[len(files)-1].GetContent())
	}
}

func contains(t *testing.T, src string, wants ...string) {
	t.Helper()
	flat := collapse(src)
	for _, want := range wants {
		if !strings.Contains(flat, collapse(want)) {
			t.Errorf("output missing %q:\n%s", want, src)
		}
	}
}

func absent(t *testing.T, src string, unwanted ...string) {
	t.Helper()
	for _, u := range unwanted {
		if strings.Contains(src, u) {
			t.Errorf("output has %q:\n%s", u, src)
		}
	}
}

func collapse(s string) string { return strings.Join(strings.Fields(s), " ") }

func structure(kind ir.StructKind, name string) *ir.Decl {
	return &ir.Decl{
		Meta: &ir.Meta{Name: name},
		Node: &ir.Decl_Structure{Structure: &ir.Struct{Kind: kind}},
	}
}

// wrote interns a collection type in the form the source wrote it.
func wrote(b *irtest.Builder, form ir.SyntacticForm, ctor string, args ...*ir.ID) *ir.ID {
	id := b.Named(ctor, args...)
	b.Model.Types[id.GetIndex()].Wrote = form
	return id
}

// Every model writes the same specification, so packages generated into
// one project declare each kind once.
func TestSpecificationIsShared(t *testing.T) {
	a := generate(t, irtest.New("shop").Model)
	b := generate(t, irtest.New("billing").Model)
	if string(a.GetFiles()[0].GetContent()) != string(b.GetFiles()[0].GetContent()) {
		t.Error("two models wrote different specifications")
	}
	contains(t, string(a.GetFiles()[0].GetContent()),
		"// Code generated by tdl. DO NOT EDIT.",
		"element entity { style { shape cylinder } }",
		"element service { style { shape component } }",
		"relationship references",
		"relationship returns",
	)
}

func TestPackageElement(t *testing.T) {
	for _, tc := range []struct {
		pkg, path, element string
	}{
		{"shop.billing", "shop_billing.c4", "package shop_billing 'shop.billing' {"},
		{"shop", "shop.c4", "package shop 'shop' {"},
		{"", "model.c4", "package model 'model' {"},
	} {
		t.Run(tc.pkg, func(t *testing.T) {
			path, src := model(t, generate(t, irtest.New(tc.pkg).Model))
			if path != tc.path {
				t.Errorf("path = %s, want %s", path, tc.path)
			}
			contains(t, src, "// Code generated by tdl. DO NOT EDIT.", "model { "+tc.element)
		})
	}
}

// Each declaration with an element gets one of the specification's kinds;
// aliases, units, and the prelude get none.
func TestElementKinds(t *testing.T) {
	b := irtest.New("shop")
	b.Own(structure(ir.StructKind_STRUCT_KIND_ENTITY, "Order"))
	b.Own(structure(ir.StructKind_STRUCT_KIND_VALUE, "Money"))
	b.Own(structure(ir.StructKind_STRUCT_KIND_MIXIN, "Timestamps"))
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "Status"}, Node: &ir.Decl_Enumeration{Enumeration: &ir.Enum{
		Variants: []*ir.Variant{{Meta: &ir.Meta{Name: "Open"}}},
	}}})
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "Sku"}, Node: &ir.Decl_Newtype{Newtype: &ir.Newtype{Base: b.Named("string")}}})
	b.Class("Priced")
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "Tags"}, Node: &ir.Decl_Alias{Alias: &ir.Alias{Target: b.Named("string")}}})
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "kg"}, Node: &ir.Decl_Unit{Unit: &ir.UnitDef{}}})

	_, src := model(t, generate(t, b.Model))
	contains(t, src,
		"entity Order 'Order' {",
		"value Money 'Money' {",
		"mixin Timestamps 'Timestamps' {",
		"enum Status 'Status' {",
		"newtype Sku 'Sku' {",
		"class Priced 'Priced' {",
	)
	absent(t, src, "Tags", "kg", "Entity", "Option", "string '")
}

func TestDescription(t *testing.T) {
	b := irtest.New("shop")
	b.Own(structure(ir.StructKind_STRUCT_KIND_ENTITY, "LineItem"))
	b.Own(structure(ir.StructKind_STRUCT_KIND_MIXIN, "Timestamps"))
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "kg"}, Node: &ir.Decl_Unit{Unit: &ir.UnitDef{}}})
	ts := b.Ref("Timestamps")

	quantity := irtest.Field("quantity", b.Named("int"))
	quantity.Constraints = []*ir.Constraint{
		{Name: "min", Args: []*ir.Literal{{Kind: ir.LiteralKind_LITERAL_KIND_INT, Text: "1"}}},
		{Name: "matches", Args: []*ir.Literal{{Kind: ir.LiteralKind_LITERAL_KIND_REGEX, Text: "^[0-9]+$"}}},
	}
	items := irtest.Field("items", wrote(b, ir.SyntacticForm_SYNTACTIC_FORM_BRACKETS, "List", b.Named("LineItem")))
	items.Owned = true
	fax := irtest.Field("fax", wrote(b, ir.SyntacticForm_SYNTACTIC_FORM_QUESTION, "Option", b.Named("string")))
	fax.Meta.Deprecated = &ir.Deprecation{}
	note := irtest.Field("note", b.Named("string"))
	note.DefaultValue = irtest.Text("none")
	created := irtest.Field("createdAt", b.Named("instant"))
	created.IncludedFrom = ts
	updated := irtest.Field("updatedAt", b.Named("instant"))
	updated.IncludedFrom = ts

	b.Own(&ir.Decl{
		Meta: &ir.Meta{
			Name:       "Order",
			Doc:        []string{" An order.", " It's placed once."},
			Deprecated: &ir.Deprecation{Reason: "use Purchase"},
		},
		Node: &ir.Decl_Structure{Structure: &ir.Struct{
			Kind: ir.StructKind_STRUCT_KIND_ENTITY,
			Fields: []*ir.Field{
				quantity, items, fax, note, created, updated,
				irtest.Field("totals", wrote(b, ir.SyntacticForm_SYNTACTIC_FORM_ARROW, "Map", b.Named("string"), b.Named("decimal"))),
				irtest.Field("tags", wrote(b, ir.SyntacticForm_SYNTACTIC_FORM_BRACES, "Set", b.Named("string"))),
				irtest.Field("shipOn", wrote(b, ir.SyntacticForm_SYNTACTIC_FORM_OR_NULL, "Nullable", b.Named("date"))),
				irtest.Field("mass", b.Named("decimal", b.Unit("kg", 3))),
			},
		}},
	})

	_, src := model(t, generate(t, b.Model))
	contains(t, src, `entity Order 'Order' {
      description '''
        An order.
        It\'s placed once.

        **Deprecated:** use Purchase

        - quantity: int where min(1) matches(/^[0-9]+$/)
        - owned items: [LineItem]
        - deprecated fax: string?
        - note: string = "none"
        - include Timestamps
        - totals: {string -> decimal}
        - tags: {string}
        - shipOn: date | null
        - mass: decimal<kg>
      '''
    }`)
	if n := strings.Count(src, "include Timestamps"); n != 1 {
		t.Errorf("include Timestamps written %d times:\n%s", n, src)
	}
}

