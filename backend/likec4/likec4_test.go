func TestTechnology(t *testing.T) {
	b := irtest.New("shop")
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "Sku"}, Node: &ir.Decl_Newtype{Newtype: &ir.Newtype{Base: b.Named("string")}}})
	b.Own(&ir.Decl{
		Meta: &ir.Meta{Name: "Page"},
		Node: &ir.Decl_Structure{Structure: &ir.Struct{
			Kind:   ir.StructKind_STRUCT_KIND_VALUE,
			Params: irtest.Params("K", "V"),
			Fields: []*ir.Field{irtest.Field("items", wrote(b, ir.SyntacticForm_SYNTACTIC_FORM_BRACKETS, "List", b.Param("V", 1)))},
		}},
	})
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "Skus"}, Node: &ir.Decl_Newtype{Newtype: &ir.Newtype{
		Base: b.Named("Page", b.Named("int"), b.Named("Sku")),
	}}})
	b.Own(structure(ir.StructKind_STRUCT_KIND_VALUE, "Plain"))

	_, src := model(t, generate(t, b.Model))
	contains(t, src,
		"newtype Sku 'Sku' { technology 'string' }",
		"technology 'Page<K, V>'",
		"- items: [V]",
		"newtype Skus 'Skus' { technology 'Page<int, Sku>' }",
		"value Plain 'Plain' { }",
	)
}

