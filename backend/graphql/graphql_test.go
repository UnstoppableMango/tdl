func generate(t *testing.T, b *irtest.Builder) *plugin.Response {
	t.Helper()
	resp, err := graphql.Backend{}.Generate(context.Background(), &plugin.Request{
		Target: graphql.Name,
		Model:  b.Model,
	})
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	return resp
}

// check returns the response's one file, and asserts it loads as a schema.
// Loading validates as well as parses, so a field naming a type a skipped
// declaration left behind fails here.
func check(t *testing.T, resp *plugin.Response) string {
	t.Helper()
	if len(resp.GetFiles()) != 1 {
		t.Fatalf("files = %d, diagnostics = %+v", len(resp.GetFiles()), resp.GetDiagnostics())
	}
	f := resp.GetFiles()[0]
	src := string(f.GetContent())
	if _, err := gqlparser.LoadSchema(&gqlast.Source{Name: f.GetPath(), Input: src}); err != nil {
		t.Errorf("%s does not load: %v\n%s", f.GetPath(), err, src)
	}
	return src
}

func contains(t *testing.T, src string, wants ...string) {
	t.Helper()
	flat := collapse(src)
	for _, want := range wants {
		if !strings.Contains(flat, collapse(want)) {
			t.Errorf("output missing %q:\n%s", want, src)
		}
	}
}

func absent(t *testing.T, src string, unwanted ...string) {
	t.Helper()
	for _, u := range unwanted {
		if strings.Contains(src, u) {
			t.Errorf("output has %q:\n%s", u, src)
		}
	}
}

func collapse(s string) string { return strings.Join(strings.Fields(s), " ") }

func value(name string, fields ...*ir.Field) *ir.Decl {
	return &ir.Decl{
		Meta: &ir.Meta{Name: name},
		Node: &ir.Decl_Structure{Structure: &ir.Struct{Kind: ir.StructKind_STRUCT_KIND_VALUE, Fields: fields}},
	}
}

func enum(name string, variants ...*ir.Variant) *ir.Decl {
	return &ir.Decl{
		Meta: &ir.Meta{Name: name},
		Node: &ir.Decl_Enumeration{Enumeration: &ir.Enum{Variants: variants}},
	}
}

func variant(name string, fields ...*ir.Field) *ir.Variant {
	return &ir.Variant{Meta: &ir.Meta{Name: name}, Fields: fields}
}

// named gives a variant's object type the GraphQL name n.
func named(v *ir.Variant, n string) *ir.Variant {
	v.Directives = []*ir.Directive{{Name: "name", Target: graphql.Name, Args: []*ir.Literal{irtest.Text(n)}}}
	return v
}

func TestDescribe(t *testing.T) {
	d := graphql.Backend{}.Describe()
	if d.Name != "graphql" || !d.Reuse {
		t.Errorf("description = %+v", d)
	}
	if len(d.Directives) != 1 || d.Directives[0].GetName() != "name" {
		t.Errorf("directives = %v", d.Directives)
	}
}

func TestObjects(t *testing.T) {
	b := irtest.New("shop.billing")
	b.Own(value("LineItem", irtest.Field("sku", b.Named("string")), irtest.Field("quantity", b.Named("int"))))
	b.Own(value("Order",
		irtest.Field("id", b.Named("uuid")),
		irtest.Field("items", b.Named("List", b.Named("LineItem"))),
		irtest.Field("tags", b.Named("Set", b.Named("string"))),
		irtest.Field("note", b.Named("Option", b.Named("string"))),
		irtest.Field("gaps", b.Named("List", b.Named("Option", b.Named("int")))),
		irtest.Field("grid", b.Named("List", b.Named("List", b.Named("int")))),
		irtest.Field("placedAt", b.Named("instant")),
		irtest.Field("paid", b.Named("bool")),
	))

	resp := generate(t, b)
	if len(resp.GetDiagnostics()) != 0 {
		t.Errorf("diagnostics = %+v", resp.GetDiagnostics())
	}
	src := check(t, resp)
	if path := resp.GetFiles()[0].GetPath(); path != "billing.graphql" {
		t.Errorf("path = %q", path)
	}
	contains(t, src,
		"# Code generated by tdl. DO NOT EDIT.",
		"type LineItem { sku: String! quantity: Long! }",
		"id: UUID!",
		"items: [LineItem!]!",
		"tags: [String!]!",
		"note: String",
		"gaps: [Long]!",
		"grid: [[Long!]!]!",
		"placedAt: DateTime!",
		"paid: Boolean!",
		"scalar DateTime",
		"scalar Long",
		"scalar UUID",
	)
	absent(t, src, "note: String!", "scalar Boolean", "scalar String")
}

func TestScalarsAreDeclaredOnlyWhenUsed(t *testing.T) {
	b := irtest.New("shop")
	b.Own(value("Note", irtest.Field("body", b.Named("string"))))
	absent(t, check(t, generate(t, b)), "scalar")
}

func TestEnums(t *testing.T) {
	b := irtest.New("shop")
	b.Own(enum("Status", variant("Active"), variant("InProgress")))
	b.Own(enum("Payment", variant("Card", irtest.Field("last4", b.Named("string"))), variant("Cash")))
	b.Own(value("Ticket", irtest.Field("status", b.Named("Status")), irtest.Field("payment", b.Named("Option", b.Named("Payment")))))

	contains(t, check(t, generate(t, b)),
		"enum Status { ACTIVE IN_PROGRESS }",
		"union Payment = PaymentCard | PaymentCash",
		"type PaymentCard { last4: String! }",
		"type PaymentCash { _: Boolean }",
		"status: Status!",
		"payment: Payment",
	)
}

func TestNewtypesExpand(t *testing.T) {
	b := irtest.New("shop")
	b.Own(&ir.Decl{Meta: &ir.Meta{Name: "Sku"}, Node: &ir.Decl_Newtype{Newtype: &ir.Newtype{Base: b.Named("string")}}})
	b.Own(value("Item", irtest.Field("sku", b.Named("Sku")), irtest.Field("skus", b.Named("List", b.Named("Sku")))))

	src := check(t, generate(t, b))
	contains(t, src, "sku: String!", "skus: [String!]!")
	absent(t, src, "Sku")
}

// A shape GraphQL cannot express is a warning, the declaration reaching it
// is skipped, and so is everything naming that declaration.
func TestUnsupportedShapesAreSkipped(t *testing.T) {
	for _, tt := range []struct {
		name  string
		build func(b *irtest.Builder) *ir.Decl
	}{
		{"a map", func(b *irtest.Builder) *ir.Decl {
			return value("Broken", irtest.Field("x", b.Named("Map", b.Named("string"), b.Named("int"))))
		}},
		{"an optional optional", func(b *irtest.Builder) *ir.Decl {
			return value("Broken", irtest.Field("x", b.Named("Nullable", b.Named("Option", b.Named("int")))))
		}},
		{"an object with no fields", func(b *irtest.Builder) *ir.Decl { return value("Broken") }},
	} {
		t.Run(tt.name, func(t *testing.T) {
			b := irtest.New("shop")
			b.Own(value("Fine", irtest.Field("a", b.Named("string"))))
			b.Own(tt.build(b))
			b.Own(value("Holder", irtest.Field("broken", b.Named("Broken"))))

			resp := generate(t, b)
			if len(resp.GetDiagnostics()) != 2 {
				t.Errorf("want a warning for Broken and one for Holder: %+v", resp.GetDiagnostics())
			}
			src := check(t, resp)
			absent(t, src, "type Broken", "type Holder")
			contains(t, src, "type Fine")
		})
	}
}

// A declaration taking a built-in scalar's name, or the name of a custom
// scalar something needs, would collide with it.
func TestScalarNames(t *testing.T) {
	b := irtest.New("shop")
	b.Own(value("ID", irtest.Field("raw", b.Named("string"))))
	b.Own(value("Long", irtest.Field("raw", b.Named("string"))))
	b.Own(value("Counter", irtest.Field("n", b.Named("int"))))

	resp := generate(t, b)
	if len(resp.GetDiagnostics()) != 2 {
		t.Errorf("want a warning for ID and one for Counter: %+v", resp.GetDiagnostics())
	}
	src := check(t, resp)
	absent(t, src, "type ID", "type Counter", "scalar Long")
	contains(t, src, "type Long")
}

// A variant's object type takes a name in the same namespace the model's
// own declarations take theirs from, so a custom scalar collides with one.
func TestScalarNamesAgainstVariants(t *testing.T) {
	b := irtest.New("shop")
	b.Own(enum("Payment",
		named(variant("Card", irtest.Field("last4", b.Named("string"))), "Long"),
		variant("Cash"),
	))
	b.Own(value("Counter", irtest.Field("n", b.Named("int"))))

	resp := generate(t, b)
	if len(resp.GetDiagnostics()) != 1 {
		t.Errorf("want a warning for Counter: %+v", resp.GetDiagnostics())
	}
	src := check(t, resp)
	absent(t, src, "type Counter", "scalar Long")
	contains(t, src, "type Long")
}

// Two variants naming their object types the same would declare one type
// twice, which the check against earlier declarations does not see.
func TestVariantsSharingAName(t *testing.T) {
	b := irtest.New("shop")
	b.Own(value("Fine", irtest.Field("a", b.Named("string"))))
	b.Own(enum("Payment",
		named(variant("Card", irtest.Field("last4", b.Named("string"))), "Tender"),
		named(variant("Cash"), "Tender"),
	))

	resp := generate(t, b)
	if len(resp.GetDiagnostics()) != 1 {
		t.Errorf("want a warning for Payment: %+v", resp.GetDiagnostics())
	}
	src := check(t, resp)
	absent(t, src, "union Payment", "type Tender")
	contains(t, src, "type Fine")
}

