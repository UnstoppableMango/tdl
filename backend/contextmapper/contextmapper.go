// Package contextmapper generates Context Mapper Language (CML) from a
// resolved model: one bounded context per package, its aggregates found
// from identity and ownership. It is a spike, not a registered backend; the
// findings are in docs/design/contextmapper-spike.md.
package contextmapper

import (
	"context"
	"fmt"
	"strconv"
	"strings"

	"github.com/unstoppablemango/tdl/backend/internal/emit"
	"github.com/unstoppablemango/tdl/ir"
	"github.com/unstoppablemango/tdl/plugin"
)

// Name names this backend in a target block.
const Name = "cml"

// Backend implements [plugin.Backend].
type Backend struct{}

func (Backend) Describe() plugin.Description {
	str := []ir.LiteralKind{ir.LiteralKind_LITERAL_KIND_STRING}
	return plugin.Description{
		Name:    Name,
		Version: "0.0.1",
		// Each request stands alone.
		Reuse: true,
		Directives: []*plugin.DirectiveSpec{
			// The bounded context's name, in place of the package's.
			{Name: "context", MinArgs: 1, MaxArgs: 1, ArgKinds: str, Placements: plugin.On(plugin.OnBlock)},
			// Field names identifying an entity, each written `key`.
			{Name: "key", MinArgs: 1, MaxArgs: -1, Placements: plugin.On(plugin.OnDecl)},
			// A value written as a DomainEvent or a CommandEvent.
			{Name: "event", Placements: plugin.On(plugin.OnDecl)},
			{Name: "command", Placements: plugin.On(plugin.OnDecl)},
		},
	}
}

const header = "// Code generated by tdl. DO NOT EDIT.\n"

// rootMark stands in an entity's text for `aggregateRoot`, written only
// when the entity roots its aggregate.
const rootMark = "\x00root\n"

// shared names the aggregate holding the objects no one aggregate claims.
const shared = "Shared"

type generator struct {
	*emit.Session

	// local is every name the bounded context declares, for references.
	local map[*ir.Decl]bool
}

// rendered is one declaration's domain objects, before they are placed in
// an aggregate.
type rendered struct {
	decl *ir.Decl
	text string
}

// Generate returns one <package id>.cml holding one bounded context.
func (Backend) Generate(_ context.Context, req *plugin.Request) (*plugin.Response, error) {
	g := &generator{Session: emit.NewSession(req, "CML"), local: map[*ir.Decl]bool{}}

	pkg := g.Model.GetPackage()
	id := packageID(pkg)
	bc := id
	if name, ok := g.Block("context"); ok {
		bc = name.GetArgs()[0].GetText()
	}

	own := g.Own()
	skipped := map[*ir.Decl]bool{}
	var out []rendered
	for _, d := range own {
		declares, err := emit.Declares(d)
		if err != nil {
			if d.GetClass() != nil {
				g.Lossy(emit.LossClass, d.GetMeta().GetPosition(), "%s is a class, and CML has no class or interface", d.GetMeta().GetName())
				continue
			}
			g.Warn(err)
			skipped[d] = true
			continue
		}
		if !declares || d.GetStructure().GetKind() == ir.StructKind_STRUCT_KIND_MIXIN {
			// A mixin's fields are copied into each including declaration.
			continue
		}
		g.local[d] = true
	}

	for _, d := range own {
		if !g.local[d] || skipped[d] {
			continue
		}
		mark := len(g.Diags)
		text, err := g.decl(d)
		if err != nil {
			g.Diags = g.Diags[:mark]
			g.Warn(err)
			skipped[d] = true
			continue
		}
		out = append(out, rendered{d, text})
	}
	g.Cascade(own, skipped)

	var kept []rendered
	for _, r := range out {
		if !skipped[r.decl] {
			kept = append(kept, r)
		}
	}
	if len(kept) == 0 {
		return g.Response(nil), nil
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n")
	if doc := emit.Doc(&ir.Meta{Doc: g.Model.GetDoc()}); len(doc) > 0 {
		for _, line := range doc {
			b.WriteString(strings.TrimRight("// "+line, " ") + "\n")
		}
	}
	fmt.Fprintf(&b, "BoundedContext %s {\n", ident(bc))
	for i, agg := range g.aggregates(kept) {
		if i > 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "  Aggregate %s {\n", ident(agg.name))
		for j, r := range agg.members {
			if j > 0 {
				b.WriteString("\n")
			}
			text := strings.Replace(r.text, rootMark, "", 1)
			if j == 0 && agg.root {
				text = strings.Replace(r.text, rootMark, "      aggregateRoot\n", 1)
			}
			b.WriteString(text)
		}
		b.WriteString("  }\n")
	}
	b.WriteString("}\n")

	return g.Response([]*plugin.File{{Path: id + ".cml", Content: []byte(b.String())}}), nil
}

// packageID joins a package's segments with _, since a bounded context's
// name is one identifier; a model with no package is "model".
func packageID(pkg string) string {
	if pkg == "" {
		return "model"
	}
	return strings.ReplaceAll(pkg, ".", "_")
}

// aggregate is one Aggregate block: a root and what it reaches.
type aggregate struct {
	name    string
	root    bool // whether members[0] is the root; Shared has none
	members []rendered
}

// aggregates partitions the rendered declarations. Every entity no other
// entity owns is a root; an entity owned by another joins its owner's
// aggregate; any other object joins the one aggregate reaching it, or,
// when none reaches it, the one aggregate whose entities it names. The rest
// go in Shared, which has no root.
func (g *generator) aggregates(kept []rendered) []aggregate {
	index := map[*ir.Decl]int{}
	for i, r := range kept {
		index[r.decl] = i
	}
	isEntity := func(d *ir.Decl) bool {
		return d.GetStructure().GetKind() == ir.StructKind_STRUCT_KIND_ENTITY
	}

	// owner maps an owned entity to the first entity owning it.
	owner := map[*ir.Decl]*ir.Decl{}
	for _, r := range kept {
		if !isEntity(r.decl) {
			continue
		}
		for _, f := range r.decl.Fields() {
			if !f.GetOwned() {
				continue
			}
			for _, t := range g.TypeReferences(f.GetType()) {
				if _, ok := index[t]; !ok || !isEntity(t) || t == r.decl {
					continue
				}
				if prev, ok := owner[t]; ok && prev != r.decl {
					g.Lossy(emit.LossOwned, f.GetMeta().GetPosition(),
						"%s is owned by %s and %s, and an aggregate has one owner; it joins %s",
						t.GetMeta().GetName(), prev.GetMeta().GetName(), r.decl.GetMeta().GetName(), prev.GetMeta().GetName())
					continue
				}
				owner[t] = r.decl
			}
		}
	}

	// root follows owners to the entity no one owns. A cycle of owners has
	// no such entity, so the first declaration met on it is the root.
	root := func(d *ir.Decl) *ir.Decl {
		seen := map[*ir.Decl]bool{}
		for {
			up, ok := owner[d]
			if !ok || seen[up] {
				return d
			}
			seen[d] = true
			d = up
		}
	}

	var aggs []aggregate
	of := map[*ir.Decl]int{} // root to its index in aggs
	home := map[*ir.Decl]int{}
	for _, r := range kept {
		if !isEntity(r.decl) {
			continue
		}
		top := root(r.decl)
		i, ok := of[top]
		if !ok {
			i = len(aggs)
			of[top] = i
			aggs = append(aggs, aggregate{name: emit.LastSegment(top.GetMeta().GetName()), root: true})
		}
		home[r.decl] = i
	}

	// reach is the set of non-entity objects each aggregate's entities
	// reach through fields, not passing through another entity.
	reached := map[*ir.Decl]map[int]bool{}
	var walk func(d *ir.Decl, agg int, seen map[*ir.Decl]bool)
	walk = func(d *ir.Decl, agg int, seen map[*ir.Decl]bool) {
		for _, t := range g.References(d) {
			if _, ok := index[t]; !ok || isEntity(t) || seen[t] {
				continue
			}
			seen[t] = true
			if reached[t] == nil {
				reached[t] = map[int]bool{}
			}
			reached[t][agg] = true
			walk(t, agg, seen)
		}
	}
	for _, r := range kept {
		if i, ok := home[r.decl]; ok {
			walk(r.decl, i, map[*ir.Decl]bool{r.decl: true})
		}
	}

	sharedAt := -1
	for _, r := range kept {
		i, ok := home[r.decl]
		if !ok {
			i, ok = only(reached[r.decl])
		}
		if !ok && len(reached[r.decl]) == 0 {
			names := map[int]bool{}
			for _, t := range g.References(r.decl) {
				if j, isHome := home[t]; isHome {
					names[j] = true
				}
			}
			i, ok = only(names)
		}
		if !ok {
			if sharedAt < 0 {
				sharedAt = len(aggs)
				aggs = append(aggs, aggregate{name: shared})
			}
			i = sharedAt
		}
		aggs[i].members = append(aggs[i].members, r)
	}

	// An aggregate's root is written first.
	for i := range aggs {
		for j, r := range aggs[i].members {
			if isEntity(r.decl) && root(r.decl) == r.decl && j > 0 {
				m := aggs[i].members
				copy(m[1:j+1], m[:j])
				m[0] = r
				break
			}
		}
	}
	return aggs
}

// only returns the one member of a set.
func only(set map[int]bool) (int, bool) {
	if len(set) != 1 {
		return 0, false
	}
	for i := range set {
		return i, true
	}
	return 0, false
}

func (g *generator) decl(d *ir.Decl) (string, error) {
	var b strings.Builder
	name := emit.LastSegment(d.GetMeta().GetName())
	switch {
	case d.GetStructure() != nil:
		kind := "ValueObject"
		switch {
		case d.GetStructure().GetKind() == ir.StructKind_STRUCT_KIND_ENTITY:
			kind = "Entity"
		case g.Tagged(d.GetDirectives(), "event"):
			kind = "DomainEvent"
		case g.Tagged(d.GetDirectives(), "command"):
			kind = "CommandEvent"
		}
		doc(&b, "    ", d.GetMeta())
		fmt.Fprintf(&b, "    %s %s {\n", kind, ident(name))
		if kind == "Entity" {
			// Whether it roots its aggregate is known once every
			// declaration is rendered.
			b.WriteString(rootMark)
		}
		keys := g.keys(d)
		for _, f := range d.Fields() {
			g.field(&b, "      ", f, keys[f.GetMeta().GetName()])
		}
		b.WriteString("    }\n")
	case d.GetEnumeration() != nil:
		return g.enum(d)
	case d.GetNewtype() != nil:
		doc(&b, "    ", d.GetMeta())
		fmt.Fprintf(&b, "    BasicType %s {\n", ident(name))
		f := &ir.Field{
			Meta:        &ir.Meta{Name: "value", Position: d.GetMeta().GetPosition()},
			Type:        d.GetNewtype().GetBase(),
			Constraints: d.GetNewtype().GetValueConstraints(),
		}
		if !g.field(&b, "      ", f, false) {
			return "", emit.Unsupported(d.GetMeta().GetPosition(), "%s wraps a type CML cannot hold", d.GetMeta().GetName())
		}
		b.WriteString("    }\n")
	}
	return b.String(), nil
}

// keys reads a `key` directive into the set of field names it marks.
func (g *generator) keys(d *ir.Decl) map[string]bool {
	dir, ok := g.Find(d.GetDirectives(), "key")
	if !ok {
		return nil
	}
	names := map[string]bool{}
	for _, f := range d.Fields() {
		names[f.GetMeta().GetName()] = false
	}
	for _, a := range dir.GetArgs() {
		n := a.GetText()
		if _, ok := names[n]; !ok {
			g.Lossy(emit.LossKey, dir.GetPosition(), "key names %s, which %s does not declare", n, d.GetMeta().GetName())
			continue
		}
		names[n] = true
	}
	return names
}

// enum writes a fieldless enum as a CML enum, and a fielded one as an
// abstract value object extended by one value object per variant.
func (g *generator) enum(d *ir.Decl) (string, error) {
	e := d.GetEnumeration()
	name := emit.LastSegment(d.GetMeta().GetName())
	pos := d.GetMeta().GetPosition()
	if len(e.GetVariants()) == 0 {
		return "", emit.Unsupported(pos, "%s has no variants, and a CML enum needs one", d.GetMeta().GetName())
	}

	var b strings.Builder
	doc(&b, "    ", d.GetMeta())
	if !emit.Fielded(e) {
		fmt.Fprintf(&b, "    enum %s {\n", ident(name))
		for i, v := range e.GetVariants() {
			doc(&b, "      ", v.GetMeta())
			b.WriteString("      " + ident(v.GetMeta().GetName()))
			if i < len(e.GetVariants())-1 {
				b.WriteString(",")
			}
			b.WriteString("\n")
		}
		b.WriteString("    }\n")
		return b.String(), nil
	}

	fmt.Fprintf(&b, "    abstract ValueObject %s {\n    }\n", ident(name))
	for _, v := range e.GetVariants() {
		b.WriteString("\n")
		doc(&b, "    ", v.GetMeta())
		fmt.Fprintf(&b, "    ValueObject %s extends @%s {\n", ident(name+v.GetMeta().GetName()), ident(name))
		for _, f := range v.GetFields() {
			g.field(&b, "      ", f, false)
		}
		b.WriteString("    }\n")
	}
	return b.String(), nil
}

// field writes one attribute or reference, or warns and writes nothing for
// a type CML cannot hold, reporting which.
func (g *generator) field(b *strings.Builder, indent string, f *ir.Field, key bool) bool {
	pos := f.GetMeta().GetPosition()
	fname := f.GetMeta().GetName()

	ref, err := g.Resolve(f.GetType())
	if err != nil {
		g.Warn(err)
		return false
	}
	nullable := false
	if ref.Form == emit.Option || ref.Form == emit.Nullable {
		nullable = true
		ref = ref.Elem
	}
	coll := ""
	switch ref.Form {
	case emit.List:
		coll = "List"
	case emit.Set:
		coll = "Set"
	}
	if coll != "" {
		ref = ref.Elem
	}

	var typ string
	isRef := false
	switch ref.Form {
	case emit.Prim:
		typ = primitive(ref.Name)
		if typ == "" {
			g.Lossy(emit.LossPrimitive, pos, "%s has no CML type, so %s is written as String", ref.Name, fname)
			typ = "String"
		}
	case emit.Named:
		if !g.local[ref.Decl] {
			g.Lossy(emit.LossUnsupported, pos, "%s names %s, which has no domain object, so the field is not written", fname, ref.Decl.GetMeta().GetName())
			return false
		}
		typ, isRef = "@"+ident(emit.LastSegment(ref.Decl.GetMeta().GetName())), true
	case emit.Map:
		g.Lossy(emit.LossCollection, pos, "%s is a map, and a CML attribute cannot be one, so the field is not written", fname)
		return false
	default:
		g.Lossy(emit.LossCollection, pos, "%s nests collections or optionals, which a CML attribute cannot, so the field is not written", fname)
		return false
	}
	if coll != "" {
		typ = coll + "<" + typ + ">"
	}

	doc(b, indent, f.GetMeta())
	b.WriteString(indent)
	if isRef {
		b.WriteString("- ")
	}
	b.WriteString(typ + " " + ident(fname))
	if key {
		b.WriteString(" key")
	}
	if nullable {
		b.WriteString(" nullable")
	}
	for _, c := range f.GetConstraints() {
		if opt := g.constraint(c, coll != "", isRef); opt != "" {
			b.WriteString(" " + opt)
		}
	}
	if f.GetDefaultValue() != nil {
		g.Lossy(emit.LossDefault, pos, "CML has no default values, so %s's default is dropped", fname)
	}
	b.WriteString("\n")
	return true
}

// constraint writes a constraint as an attribute's validation option, or
// warns that CML has none for it. A reference takes only size.
func (g *generator) constraint(c *ir.Constraint, coll, isRef bool) string {
	arg := func() *ir.Literal {
		if len(c.GetArgs()) == 1 {
			return c.GetArgs()[0]
		}
		return nil
	}
	switch c.GetName() {
	case "min", "max":
		if a := arg(); a != nil && !isRef && !coll {
			return c.GetName() + " = " + quote(emit.LiteralText(a))
		}
	case "length":
		// CML's length and size take one number, the most allowed, and
		// notEmpty is the only lower bound it states.
		if a := arg(); a != nil && (coll || !isRef) {
			low, high, err := emit.Length(a)
			if err != nil {
				break
			}
			var opts []string
			if low != nil && *low == 1 {
				opts = append(opts, "notEmpty")
			} else if low != nil && *low > 1 {
				g.Lossy(emit.LossConstraint, c.GetPosition(), "CML states no lower length bound but 1, so %s keeps only its upper bound", emit.ConstraintText(c))
			}
			if high != nil {
				opt := "length"
				if coll {
					opt = "size"
				}
				opts = append(opts, opt+" = "+quote(strconv.FormatInt(*high, 10)))
			}
			if len(opts) > 0 {
				return strings.Join(opts, " ")
			}
		}
	case "matches":
		if a := arg(); a != nil && !isRef && !coll {
			// Written as the source spells it: RE2, which Java's
			// regular expressions read alike for the common cases.
			if _, err := emit.Pattern(a); err == nil {
				return "pattern = " + quote(a.GetText())
			}
		}
	}
	g.Lossy(emit.LossConstraint, c.GetPosition(), "CML has no option for %s here, so it is dropped", emit.ConstraintText(c))
	return ""
}

// primitive is the CML type for a prelude primitive, or "" for one CML
// lacks.
func primitive(name string) string {
	switch name {
	case "string":
		return "String"
	case "int", "int64":
		return "Long"
	case "int32":
		return "Integer"
	case "uint32":
		return "Long"
	case "uint64":
		return "BigInteger"
	case "float32":
		return "Float"
	case "float64":
		return "Double"
	case "bool":
		return "Boolean"
	case "bytes":
		return "Blob"
	case "decimal":
		return "BigDecimal"
	case "date":
		return "Date"
	case "instant":
		return "Timestamp"
	case "uuid":
		return "UUID"
	case "duration":
		return "Duration"
	}
	return ""
}

// doc writes a doc comment, and a deprecation, as the doc string CML puts
// before a domain object or an attribute.
func doc(b *strings.Builder, indent string, m *ir.Meta) {
	lines := emit.Doc(m)
	if reason, ok := emit.Deprecated(m); ok {
		line := "Deprecated."
		if reason != "" {
			line = "Deprecated: " + reason
		}
		lines = append(lines, line)
	}
	if len(lines) == 0 {
		return
	}
	b.WriteString(indent + quote(strings.Join(lines, "\n")) + "\n")
}

// quote writes a double-quoted CML string.
func quote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`).Replace(s) + `"`
}

// ident escapes a name CML reserves with ^, as Xtext does.
func ident(name string) string {
	if keywords[name] {
		return "^" + name
	}
	return name
}
