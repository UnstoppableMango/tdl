package nix_test

import (
	"context"
	"os/exec"
	"strings"
	"testing"

	"github.com/unstoppablemango/tdl/backend/nix"
	"github.com/unstoppablemango/tdl/internal/sema"
	"github.com/unstoppablemango/tdl/parser"
	"github.com/unstoppablemango/tdl/plugin"
)

// gen generates source and returns the response and its one file, which it
// holds to nixfmt when nixfmt is on PATH.
func gen(t *testing.T, src string) (*plugin.Response, string) {
	t.Helper()
	file, err := parser.Parse("shop.tdl", strings.NewReader(src))
	if err != nil {
		t.Fatal(err)
	}
	m, diags := sema.Lower(file)
	if len(diags) > 0 {
		t.Fatal(diags.Error())
	}
	resp, err := nix.Backend{}.Generate(context.Background(), &plugin.Request{Target: nix.Name, Model: m})
	if err != nil {
		t.Fatal(err)
	}
	if len(resp.GetFiles()) != 1 {
		t.Fatalf("files = %d, diagnostics = %v", len(resp.GetFiles()), resp.GetDiagnostics())
	}
	out := string(resp.GetFiles()[0].GetContent())
	if path, err := exec.LookPath("nixfmt"); err == nil {
		cmd := exec.Command(path, "--check", "-")
		cmd.Stdin = strings.NewReader(out)
		if b, err := cmd.CombinedOutput(); err != nil {
			t.Errorf("nixfmt --check: %v\n%s\n%s", err, b, out)
		}
	}
	return resp, out
}

// warned reports whether a warning carries code and mentions word.
func warned(resp *plugin.Response, code, word string) bool {
	for _, d := range resp.GetDiagnostics() {
		if d.GetCode() == code && strings.Contains(d.GetMessage(), word) {
			return true
		}
	}
	return false
}

func warns(t *testing.T, resp *plugin.Response, want ...[2]string) {
	t.Helper()
	for _, w := range want {
		if !warned(resp, w[0], w[1]) {
			t.Errorf("no %q warning about %s: %v", w[0], w[1], resp.GetDiagnostics())
		}
	}
}

// contains checks for each of wants with whitespace collapsed.
func contains(t *testing.T, out string, wants ...string) {
	t.Helper()
	flat := strings.Join(strings.Fields(out), " ")
	for _, w := range wants {
		if !strings.Contains(flat, strings.Join(strings.Fields(w), " ")) {
			t.Errorf("output missing %q:\n%s", w, out)
		}
	}
}

func TestEnum(t *testing.T) {
	resp, out := gen(t, `package shop.billing
/// Where an order is.
enum Status { Draft deprecated("gone") Placed }
enum Never { }
target nix for shop.billing { Status.Draft => wire("draft") }
`)
	if p := resp.GetFiles()[0].GetPath(); p != "shop/billing.nix" {
		t.Errorf("path = %s", p)
	}
	contains(t, out,
		"# Code generated by tdl. DO NOT EDIT.\n{ lib }:\nlet\n  inherit (lib) types mkOption;\nin\nrec {",
		`# Where an order is.
  Status = types.enum [ "draft" # Deprecated: gone "Placed" ];`,
		"Never = types.enum [ ];",
	)
}

func TestFileDirective(t *testing.T) {
	resp, _ := gen(t, "package shop\nenum A { B }\ntarget nix for shop { file(\"types.nix\") }\n")
	if p := resp.GetFiles()[0].GetPath(); p != "types.nix" {
		t.Errorf("path = %s", p)
	}
}

func TestBindings(t *testing.T) {
	resp, out := gen(t, `package shop
enum A { X }
enum B { X }
enum C { X }
enum D { X }
target nix for shop {
  B => name("types")
  C => name("if")
  D => name("A")
}
`)
	if strings.Contains(out, "types =") || strings.Contains(out, "if =") || strings.Count(out, "A =") != 1 {
		t.Errorf("output binds a name it must not:\n%s", out)
	}
	warns(t, resp, [2]string{"", "which the file binds itself"}, [2]string{"", "not a Nix identifier"}, [2]string{"", "and A already is"})
}

func TestSkipsWhatPhaseOneLacks(t *testing.T) {
	resp, out := gen(t, `package shop
type Id: string
enum Payment { Card { last4: string } Cash }
class Audited { at: string }
alias Ids = [string]
enum Kept { X }
`)
	for _, name := range []string{"Id =", "Payment", "Audited", "Ids"} {
		if strings.Contains(out, name) {
			t.Errorf("output has %s:\n%s", name, out)
		}
	}
	warns(t, resp, [2]string{"", "Id is a newtype"}, [2]string{"", "Payment has variants"},
		[2]string{"lossy.class", "Audited"}, [2]string{"lossy.alias", "Ids"})
}
