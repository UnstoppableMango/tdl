// Package nix generates nixpkgs lib.types option types from a resolved
// model. A value of a generated type is the JSON wire convention, so
// builtins.toJSON writes what the other JSON targets read.
package nix

import (
	"context"
	"fmt"
	"maps"
	"regexp"
	"slices"
	"strings"

	"github.com/unstoppablemango/tdl/backend/internal/emit"
	"github.com/unstoppablemango/tdl/ir"
	"github.com/unstoppablemango/tdl/plugin"
)

// Name names this backend in a target block and as tdl-gen-nix.
const Name = "nix"

// Backend implements [plugin.Backend].
type Backend struct{}

func (Backend) Describe() plugin.Description {
	str := []ir.LiteralKind{ir.LiteralKind_LITERAL_KIND_STRING}
	return plugin.Description{
		Name:    Name,
		Version: "0.1.0",
		Reuse:   true,
		Directives: []*plugin.DirectiveSpec{
			// A declaration's attribute in the file's set. On a field it
			// renames the attribute and warns, since wire renames a JSON key.
			{Name: "name", MinArgs: 1, MaxArgs: 1, ArgKinds: str, Placements: plugin.OnMembers()},
			// A field's attribute and a variant's tag on the wire.
			{Name: "wire", MinArgs: 1, MaxArgs: 1, ArgKinds: str, Placements: plugin.On(plugin.OnField, plugin.OnVariant)},
			// The file's path under out.
			{Name: "file", MinArgs: 1, MaxArgs: 1, ArgKinds: str, Placements: plugin.On(plugin.OnBlock)},
		},
	}
}

var ident = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_'-]*$`)

// keywords cannot name a binding.
var keywords = []string{"assert", "else", "if", "in", "inherit", "let", "or", "rec", "then", "with"}

// helper is a binding the file declares when a type uses it.
type helper struct{ name, text string }

// helpers is every helper, in the order the file declares them.
var helpers = []helper{
	{"after", afterHelper},
	{"struct", structHelper},
	{"optional", optionalHelper},
	{"nullable", "  nullable = type: types.nullOr type // { emptyValue = { }; };\n"},
	{"duration", durationHelper},
	{"set", setHelper},
	{"keyed", "  keyed = key: value: types.addCheck (types.attrsOf value) (m: lib.all key.check (lib.attrNames m));\n"},
}

type generator struct {
	*emit.Session

	// used is the helpers the declaration being rendered uses.
	used map[string]bool
}

// Generate returns one .nix file: a function of lib returning an attribute
// set of option types, one per declaration.
func (Backend) Generate(_ context.Context, req *plugin.Request) (*plugin.Response, error) {
	g := &generator{Session: emit.NewSession(req, "Nix")}
	own := g.Own()
	text := map[*ir.Decl]string{}
	used := map[*ir.Decl]map[string]bool{}
	skipped := map[*ir.Decl]bool{}
	for _, d := range own {
		mark := len(g.Diags)
		g.used = map[string]bool{}
		s, err := g.decl(d)
		if err != nil {
			g.Diags = g.Diags[:mark]
			g.Skip(err)
			skipped[d] = true
			continue
		}
		text[d], used[d] = s, g.used
	}
	g.Cascade(own, skipped)
	// A name goes to the first declaration still generated, and a later
	// one taking it is skipped with what names it.
	names := map[string]string{}
	for _, d := range own {
		if skipped[d] || text[d] == "" {
			continue
		}
		attr, name := g.attr(d), d.GetMeta().GetName()
		if other, ok := names[attr]; ok {
			g.Skip(emit.Unsupported(d.GetMeta().GetPosition(), "%s would be bound as %s, and %s already is", name, attr, other))
			skipped[d] = true
			continue
		}
		names[attr] = name
	}
	g.Cascade(own, skipped)

	var body []string
	helped := map[string]bool{}
	for _, d := range own {
		if !skipped[d] && text[d] != "" {
			body = append(body, text[d])
			maps.Copy(helped, used[d])
		}
	}
	if len(body) == 0 {
		return g.Response(nil), nil
	}

	var b strings.Builder
	b.WriteString("# Code generated by tdl. DO NOT EDIT.\n{ lib }:\nlet\n  inherit (lib) types mkOption;\n")
	for _, h := range helpers {
		if helped[h.name] {
			b.WriteString(h.text)
		}
	}
	b.WriteString("in\nrec {\n")
	b.WriteString(strings.Join(body, "\n"))
	b.WriteString("}\n")

	path := "model.nix"
	if pkg := req.GetModel().GetPackage(); pkg != "" {
		path = strings.ReplaceAll(pkg, ".", "/") + ".nix"
	}
	if f, ok := g.Block("file"); ok {
		path = f.GetArgs()[0].GetText()
	}
	return g.Response([]*plugin.File{{Path: path, Content: []byte(b.String())}}), nil
}

// decl renders one declaration's binding, or "" for one that declares
// nothing.
func (g *generator) decl(d *ir.Decl) (string, error) {
	pos, name := d.GetMeta().GetPosition(), d.GetMeta().GetName()
	if ok, err := g.DeclaresLossy(d, func(*ir.ID) {}); !ok {
		return "", err
	}
	e := d.GetEnumeration()
	switch {
	case d.GetNewtype() != nil:
		return "", emit.Unsupported(pos, "%s is a newtype, and newtypes are not generated yet", name)
	case e != nil && emit.Fielded(e):
		return "", emit.Unsupported(pos, "%s has variants carrying fields, and those are not generated yet", name)
	}

	attr := g.attr(d)
	switch {
	case !ident.MatchString(attr) || slices.Contains(keywords, attr):
		return "", emit.Unsupported(pos, "%s would be bound as %q, which is not a Nix identifier", name, attr)
	}
	g.LoseConforms(d, "Nix")

	var b strings.Builder
	comment(&b, "  ", d.GetMeta())
	var err error
	if e != nil {
		err = g.enum(&b, d, attr)
	} else {
		err = g.structure(&b, d, attr)
	}
	if err != nil {
		return "", err
	}
	g.WarnConstraints(d)
	return b.String(), nil
}

// attr is a declaration's attribute in the file's set.
func (g *generator) attr(d *ir.Decl) string {
	return g.DeclName(d, func(s string) string { return s })
}

// enum renders an enum whose variants carry no fields as the enum of its
// wire values.
func (g *generator) enum(b *strings.Builder, d *ir.Decl, attr string) error {
	if err := g.CheckTags(d); err != nil {
		return err
	}
	variants := d.GetEnumeration().GetVariants()
	if len(variants) == 0 {
		fmt.Fprintf(b, "  %s = types.enum [ ];\n", attr)
		return nil
	}
	fmt.Fprintf(b, "  %s = types.enum [\n", attr)
	for _, v := range variants {
		comment(b, "    ", v.GetMeta())
		fmt.Fprintf(b, "    %s\n", str(g.Tag(v)))
	}
	b.WriteString("  ];\n")
	return nil
}

// description is a node's doc comment and deprecation, as an option's
// description.
func description(m *ir.Meta) string {
	lines := emit.Doc(m)
	if reason, ok := emit.Deprecated(m); ok {
		if len(lines) > 0 {
			lines = append(lines, "")
		}
		if reason == "" {
			lines = append(lines, "Deprecated.")
		} else {
			lines = append(lines, "Deprecated: "+reason)
		}
	}
	return strings.Join(lines, "\n")
}

// comment writes a node's description as # lines.
func comment(b *strings.Builder, indent string, m *ir.Meta) {
	doc := description(m)
	if doc == "" {
		return
	}
	for line := range strings.SplitSeq(doc, "\n") {
		fmt.Fprintf(b, "%s%s\n", indent, strings.TrimRight("# "+line, " "))
	}
}

// str is a Nix string literal.
func str(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "${", `\${`, "\n", `\n`, "\r", `\r`, "\t", `\t`)
	return `"` + r.Replace(s) + `"`
}
