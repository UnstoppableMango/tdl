	[Theory]
	[InlineData("namespace/nopackage", "needs a name")]
	[InlineData("namespace/keyword", "not a C# namespace")]
	[InlineData("namespace/empty", "not a C# namespace")]
	public void NamespaceThatCannotBeUsed(string name, string want)
	{
		var resp = Generate(name);
		Assert.Empty(resp.Files);
		var d = Assert.Single(resp.Diagnostics);
		Assert.Equal(Severity.Error, d.Severity);
		Assert.Contains(want, d.Message, StringComparison.Ordinal);
	}

