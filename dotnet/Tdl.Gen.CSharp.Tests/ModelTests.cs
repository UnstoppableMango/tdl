		Absent(File(resp, "LineItem.g.cs"), "Equals", "TdlEquality");
		Contains(File(resp, "LineItem.g.cs"), "    public required long Quantity { get; init; }\n");
		Contains(File(resp, "Marker.g.cs"), "public sealed partial record Marker;\n");
		Contains(File(resp, "TdlEquality.g.cs"), "internal static class TdlEquality\n");
	}

