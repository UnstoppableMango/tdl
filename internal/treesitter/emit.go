// Package treesitter turns the annotated grammar into a tree-sitter
// grammar.js.
//
// The two files say the same thing in two notations, and this is the
// translation: internal/ebnf reads docs/grammar.ebnf and knows nothing
// about tree-sitter, and nothing here reads the notation. What the EBNF
// cannot state, the annotations do; see docs/design/treesitter.md.
package treesitter

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	xebnf "golang.org/x/exp/ebnf"

	"github.com/unstoppablemango/tdl/internal/ebnf"
)

// grammarName is what the generated parser calls itself, which becomes
// tree_sitter_tdl() in the C it generates.
const grammarName = "tdl"

const header = `// Code generated by tools/treesitter from docs/grammar.ebnf. DO NOT EDIT.
//
// The grammar is derived rather than written: docs/design/treesitter.md
// says why, and docs/grammar.ebnf is the file to change.

/// <reference types="tree-sitter-cli/dsl" />
// @ts-check

`

type emitter struct {
	file  *ebnf.File
	order []*xebnf.Production // file order, since a Grammar is a map
	rules map[string]string   // EBNF name to tree-sitter rule
	b     strings.Builder

	// inlining is what substitute is in the middle of, so a rule that
	// inlines itself is an error rather than a stack overflow.
	inlining map[string]bool
}

// Emit writes grammar.js for a grammar internal/ebnf has already read and
// found clean.
func Emit(file *ebnf.File) ([]byte, error) {
	e := &emitter{
		file:     file,
		order:    fileOrder(file.Grammar),
		inlining: map[string]bool{},
	}
	if err := e.buildNames(); err != nil {
		return nil, err
	}
	if err := e.grammar(); err != nil {
		return nil, err
	}
	return []byte(e.b.String()), nil
}

// fileOrder is the order the productions are written in. Emitting them
// any other way would still be deterministic and would make the diff
// against docs/grammar.ebnf unreadable.
func fileOrder(grammar xebnf.Grammar) []*xebnf.Production {
	out := make([]*xebnf.Production, 0, len(grammar))
	for _, prod := range grammar {
		out = append(out, prod)
	}
	sort.Slice(out, func(i, j int) bool {
		return out[i].Name.Pos().Offset < out[j].Name.Pos().Offset
	})
	return out
}

func (e *emitter) grammar() error {
	a := e.file.Annotations

	e.b.WriteString(header)
	e.b.WriteString("module.exports = grammar({\n")
	e.line(1, "name: %s,", quote(grammarName))

	if a.Word != "" {
		ref, err := e.ref(a.Word)
		if err != nil {
			return fmt.Errorf("word: %w", err)
		}
		e.line(1, "word: $ => %s,", ref)
	}

	// Whitespace is not in the grammar because the EBNF has no way to say
	// it: an item ends where the next begins.
	extras := []string{`/\s/`}
	for _, name := range a.Extras {
		ref, err := e.ref(name)
		if err != nil {
			return fmt.Errorf("extra: %w", err)
		}
		extras = append(extras, ref)
	}
	e.list("extras", extras)

	if err := e.externals(); err != nil {
		return err
	}
	if err := e.conflicts(); err != nil {
		return err
	}
	if err := e.body(); err != nil {
		return err
	}

	e.b.WriteString("});\n")
	return nil
}

func (e *emitter) externals() error {
	var refs []string
	for _, prod := range e.order {
		if !e.file.Annotations.Prods[prod.Name.String].External {
			continue
		}
		ref, err := e.ref(prod.Name.String)
		if err != nil {
			return err
		}
		refs = append(refs, ref)
	}
	if len(refs) > 0 {
		e.list("externals", refs)
	}
	return nil
}

func (e *emitter) conflicts() error {
	pairs := e.file.Annotations.Conflicts
	if len(pairs) == 0 {
		return nil
	}

	e.line(1, "conflicts: $ => [")
	for _, pair := range pairs {
		refs := make([]string, len(pair))
		for i, name := range pair {
			ref, err := e.ref(name)
			if err != nil {
				return fmt.Errorf("conflict: %w", err)
			}
			refs[i] = ref
		}
		e.line(2, "[%s],", strings.Join(refs, ", "))
	}
	e.line(1, "],")
	return nil
}

func (e *emitter) body() error {
	e.line(1, "rules: {")

	for _, prod := range e.order {
		name := prod.Name.String
		ann := e.file.Annotations.Prods[name]
		switch {
		case ann.External:
			continue // the scanner produces it; the grammar only names it
		case ann.Inline:
			continue // substitute put it wherever it was used
		}

		body, err := e.rule(prod, ann)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		e.write(body, e.rules[name])
	}

	// The comment terminals: named by an extra, defined by a file-level
	// token binding, and mentioned nowhere in the grammar itself.
	for _, name := range e.file.Annotations.Extras {
		if _, ok := e.file.Grammar[name]; ok {
			continue
		}
		e.write(leaf(regex(e.file.Annotations.Tokens[name])), e.rules[name])
	}

	e.line(1, "},")
	return nil
}

// rule is one production's body, precedence and all.
func (e *emitter) rule(prod *xebnf.Production, ann ebnf.ProdAnnotations) (expr, error) {
	var body expr
	if prod.Expr == nil {
		// The lexer's, and the token annotation says which part of it.
		if ann.Token == "" {
			return nil, fmt.Errorf("no expression and no token annotation")
		}
		body = leaf(regex(ann.Token))
	} else {
		var err error
		if body, err = e.convert(prod.Expr); err != nil {
			return nil, err
		}
	}

	if ann.HasPrec {
		fn := "prec"
		if ann.Assoc != "" {
			fn += "." + ann.Assoc
		}
		body = call{fn, []expr{leaf(strconv.Itoa(ann.Prec)), body}}
	}
	return body, nil
}

// convert is the whole translation, one node at a time.
func (e *emitter) convert(x xebnf.Expression) (expr, error) {
	switch n := x.(type) {
	case xebnf.Alternative:
		return e.combinator("choice", n)
	case xebnf.Sequence:
		return e.combinator("seq", n)
	case *xebnf.Name:
		if e.file.Annotations.Prods[n.String].Inline {
			return e.substitute(n)
		}
		ref, err := e.ref(n.String)
		return leaf(ref), err
	case *xebnf.Token:
		return leaf(quote(n.String)), nil
	case *xebnf.Group:
		// Parentheses group; a combinator call needs no help doing that.
		return e.convert(n.Body)
	case *xebnf.Option:
		return e.wrap("optional", n.Body)
	case *xebnf.Repetition:
		return e.wrap("repeat", n.Body)
	case *xebnf.Range:
		return nil, fmt.Errorf("%s: a character range has no tree-sitter spelling", n.Pos())
	case *xebnf.Bad:
		return nil, fmt.Errorf("%s: %s", n.Pos(), n.Error)
	default:
		return nil, fmt.Errorf("%s: unexpected %T", x.Pos(), x)
	}
}

// substitute puts an inline production's body where its name was.
//
// tree-sitter has an inline array meaning the same thing, and it refuses a
// rule that is a single token, which FieldRel is. Substituting here says
// what the annotation says for every rule rather than for some of them.
func (e *emitter) substitute(n *xebnf.Name) (expr, error) {
	if e.inlining[n.String] {
		return nil, fmt.Errorf("%s: %s is inline and refers to itself", n.Pos(), n.String)
	}
	e.inlining[n.String] = true
	defer delete(e.inlining, n.String)

	return e.convert(e.file.Grammar[n.String].Expr)
}

func (e *emitter) combinator(fn string, parts []xebnf.Expression) (expr, error) {
	args := make([]expr, len(parts))
	for i, part := range parts {
		arg, err := e.convert(part)
		if err != nil {
			return nil, err
		}
		args[i] = arg
	}
	if len(args) == 1 {
		return args[0], nil // a choice of one is the one
	}
	return call{fn, args}, nil
}

func (e *emitter) wrap(fn string, body xebnf.Expression) (expr, error) {
	arg, err := e.convert(body)
	if err != nil {
		return nil, err
	}
	return call{fn, []expr{arg}}, nil
}

// write emits one rule, broken over lines if it does not fit.
func (e *emitter) write(body expr, rule string) {
	const indent = "    "
	prefix := rule + ": $ => "
	e.b.WriteString(indent)
	e.b.WriteString(prefix)
	e.b.WriteString(render(body, indent, prefix))
	e.b.WriteString(",\n")
}

func (e *emitter) line(depth int, format string, args ...any) {
	e.b.WriteString(strings.Repeat("  ", depth))
	fmt.Fprintf(&e.b, format, args...)
	e.b.WriteByte('\n')
}

func (e *emitter) list(name string, items []string) {
	e.line(1, "%s: $ => [%s],", name, strings.Join(items, ", "))
}
